def convert(op: str, key: str, val: str):
    ints = {"id", "amount", "day"}
    lists = {"ids", "amounts"}
    if key in ints:
        return int(val)
    if key in lists:
        return [int(x) for x in val.split(",")]
    if key == "approved" and op == "set_operator":
        return val == "true"
    return val


def run_op(m: Model, op: str, args: dict):
    fn = getattr(m, op)
    fn(**{k: convert(op, k, v) for k, v in args.items()})


# ---------------------------------------------------------- fixture


def parse_fixture():
    digest = None
    vectors = []
    cur = None
    for line in FIXTURE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        k, _, v = line.partition("=")
        if k == "digest" and cur is None:
            digest = v
        elif k == "vector":
            if cur is not None:
                vectors.append(cur)
            cur = {"id": v, "op": None, "args": {}, "status": None,
                   "err": None, "reads": {}}
        elif k == "op":
            cur["op"] = v
        elif k == "status":
            cur["status"] = v
        elif k == "err":
            cur["err"] = v
        elif k.startswith("read."):
            cur["reads"][k[len("read."):]] = v
        else:
            cur["args"][k] = v
    if cur is not None:
        vectors.append(cur)
    return digest, vectors


def canonical(v) -> str:
    reads = " ".join(f"{k}={val}" for k, val in sorted(v["reads"].items()))
    status = v["status"] if v["status"] == "ok" else f"err:{v['err']}"
    return f"{v['id']}|{v['op']}|{status}|{reads}"


def execute_vectors(vectors):
    m = Model()
    for v in vectors:
        try:
            run_op(m, v["op"], v["args"])
            got = "ok"
            err = None
        except E8Error as e:
            got = "err"
            err = str(e)
        if v["status"] == "ok":
            assert got == "ok", f"{v['id']}: expected ok, got {err}"
        else:
            assert got == "err" and err == v["err"], (
                f"{v['id']}: expected {v['err']!r}, got {err!r}")
        for key, want in v["reads"].items():
            assert m.query(key) == want, f"{v['id']}: read {key}"
    return m


# -------------------------------------------------------- DAO mirror


def dao_scenario():
    stakes = [250_000 * ALCRY, 150_000 * ALCRY, 100_000 * ALCRY,
              75_000 * ALCRY, 25_000 * ALCRY]
    labels = ["alice", "bob", "carol", "dave", "eve"]
    snapshot = list(stakes)
    votes: list[tuple[int, str, int]] = []   # (voter, support, power)
    seen: set[int] = set()
    steps = []
    steps.append("propose|1|proposer=0|created=1000")

    def cast(voter, support, height):
        if voter in seen:
            raise E8Error(f"E8: vote already cast (1/{voter})")
        power = snapshot[voter]
        if power == 0:
            raise E8Error(f"E8: no voting power ({voter})")
        if height >= 1000 + 120_960:
            raise E8Error(f"E8: voting closed (1)")
        seen.add(voter)
        votes.append((voter, support, power))

    first = None
    for voter, support, height, word in [
        (1, "yes", 2000, "yes"), (2, "yes", 3000, "yes"),
        (3, "no", 4000, "no"), (4, "abstain", 5000, "abstain"),
    ]:
        cast(voter, support, height)
        if first is None:
            first = (1, voter, support, votes[-1][2])
        steps.append(f"vote|1|{voter}|{word}|{votes[-1][2]}")
    try:
        cast(1, "yes", 6000)
        raise AssertionError("double vote must fail")
    except E8Error as e:
        steps.append(f"vote_err|1|1|{e}")

    yes = sum(p for (_, s, p) in votes if s == "yes")
    no = sum(p for (_, s, p) in votes if s == "no")
    abstain = sum(p for (_, s, p) in votes if s == "abstain")
    total = yes + no + abstain
    quorum = sum(snapshot) * 2000 // 10_000
    passed = total >= quorum and yes > no
    steps.append(f"finalize|1|{'passed' if passed else 'rejected'}")
    steps.append("execute|1|executed")
    return {
        "steps": steps,
        "first": first,
        "ui_votes": len(votes),
        "tally": (yes, no, abstain),
        "labels": labels,
        "votes": votes,
        "snapshot": snapshot,
        "heights": [2000, 3000, 4000, 5000],
        "created": 1000,
    }


def render_html(dao) -> str:
    """Byte-identical mirror of DaoUi::render_html for the scenario."""
    yes, no, abstain = dao["tally"]
    total = yes + no + abstain
    pct = yes * 100 // total if total else 0
    state = "executed"
    lines = [
        "<!doctype html>",
        '<html lang="en">',
        "<head>",
        '<meta charset="utf-8">',
        "<title>AuraLite DAO — governance UI</title>",
        "<style>",
        "body{font-family:sans-serif;background:#0f1220;color:#e8eaf6;margin:2rem;max-width:52rem}",
        "h1{font-size:1.4rem}",
        ".card{background:#1a1f36;border-radius:10px;padding:1rem 1.2rem;margin:1rem 0}",
        ".badge{padding:.15rem .6rem;border-radius:999px;font-size:.8rem;background:#2b3157}",
        ".passed{background:#1b5e20}.executed{background:#00695c}.rejected{background:#7f1d1d}",
        "table{width:100%;border-collapse:collapse;font-size:.9rem}",
        "td,th{padding:.35rem .5rem;text-align:left;border-bottom:1px solid #2b3157}",
        ".meter{background:#2b3157;border-radius:6px;height:.6rem;margin:.25rem 0}",
        ".meter i{display:block;height:100%;border-radius:6px;background:#7c86ff}",
        ".foot{opacity:.7;font-size:.8rem;margin-top:1.5rem}",
        "</style>",
        "</head>",
        "<body>",
        "<h1>AuraLite DAO — governance UI</h1>",
        f'<div class="card"><strong>Proposal #1</strong> <span class="badge {state}">{state}</span>',
        f"<div>proposer: {dao['labels'][0]} &middot; created at block {dao['created']}</div>",
        f'<div class="meter"><i style="width:{pct}%"></i></div>',
        "<table><tr><th>yes</th><th>no</th><th>abstain</th></tr>",
        f"<tr><td>{yes // ALCRY} ALCRY</td><td>{no // ALCRY} ALCRY</td><td>{abstain // ALCRY} ALCRY</td></tr>",
        "</table></div>",
        '<div class="card"><strong>Votes through the UI</strong>',
        "<table><tr><th>#</th><th>proposal</th><th>voter</th><th>support</th><th>power</th></tr>",
    ]
    for i, ((voter, support, power), _h) in enumerate(
        zip(dao["votes"], dao["heights"]), 1
    ):
        lines.append(
            f"<tr><td>{i}</td><td>#1</td><td>{dao['labels'][voter]}</td>"
            f"<td>{support}</td><td>{power // ALCRY} ALCRY</td></tr>"
        )
    lines += [
        "</table></div>",
        f'<div class="foot">{len(dao["votes"])} vote receipts &middot; '
        "rendered by AuraLite governance UI (E8)</div>",
        "</body>",
        "</html>",
    ]
    return "".join(line + "\n" for line in lines)


def main() -> int:
    digest, vectors = parse_fixture()
    assert digest == VECTORS_DIGEST, "fixture digest"
    assert len(vectors) == 50, f"50 vectors, got {len(vectors)}"
    execute_vectors(vectors)
    rebuilt = hashlib.sha256(
        ";".join(canonical(v) for v in vectors).encode()
    ).hexdigest()
    assert rebuilt == VECTORS_DIGEST, f"rebuilt digest {rebuilt}"

    dao = dao_scenario()
    assert dao["steps"][5] == "vote_err|1|1|E8: vote already cast (1/1)"
    scenario_digest = hashlib.sha256(";".join(dao["steps"]).encode()).hexdigest()
    assert scenario_digest == SCENARIO_DIGEST, f"scenario {scenario_digest}"
    assert dao["first"] == (1, 1, "yes", 150_000 * ALCRY)
    assert dao["ui_votes"] == 4
    assert dao["tally"] == (
        250_000 * ALCRY, 75_000 * ALCRY, 25_000 * ALCRY,
    )

    html = render_html(dao)
    ui_sha = hashlib.sha256(html.encode()).hexdigest()
    assert ui_sha == UI_HTML_SHA, f"ui html {ui_sha}"

    # The exact three lines the Rust example prints.
    print(f"E8-VECTORS-OK {len(vectors)}")
    print(f"E8-UI-OK {ui_sha}")
    print(f"E8-SIM-OK {SIM_LINE}")

    sim = {
        "vectors": 50,
        "vectors_digest": VECTORS_DIGEST,
        "scenario_digest": SCENARIO_DIGEST,
        "aggregate_digest":
            "39674d6a0813cb9beae5837025e1a8b6c00fb8ebe1bc620a06e844a5829fb313",
        "ui_html_sha256": ui_sha,
        "first_vote": [1, 1, "yes"],
        "ui_votes": 4,
        "tally": {
            "yes": 250_000 * ALCRY,
            "no": 75_000 * ALCRY,
            "abstain": 25_000 * ALCRY,
        },
        "state": "executed",
        "stakes_alcry": [250_000, 150_000, 100_000, 75_000, 25_000],
    }
    (REPO / "sim/e8-dao.json").write_text(
        json.dumps(sim, indent=2) + "\n", encoding="utf-8"
    )
    (REPO / "sim/e8-governance-ui.html").write_text(html, encoding="utf-8")
    return 0


