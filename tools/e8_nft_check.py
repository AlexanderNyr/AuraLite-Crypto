#!/usr/bin/env python3
"""E8 NFT + names + identity + DAO UI deterministic model check
(ECOSYSTEM_PLAN E8).

Independent Python model for `crates/aura-storage/src/nft.rs` +
`src/dao_ui.rs`. It re-executes the pinned golden fixture
`crates/aura-storage/tests/fixtures/e8-standards.txt` (50 standard
vectors, generated by `tools/gen_e8_vectors.py`), rebuilds the vectors
digest, replays the DAO scenario (the first vote cast through the UI),
mirrors the governance UI HTML byte for byte and prints exactly the
three pinned lines the Rust example
`crates/aura-storage/examples/e8_nft_example.rs` prints:

    E8-VECTORS-OK 50
    E8-UI-OK <sha256 of governance-ui.html>
    E8-SIM-OK {"vectors": 50, ...}

Writes `sim/e8-dao.json` and `sim/e8-governance-ui.html`.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FIXTURE = REPO / "crates/aura-storage/tests/fixtures/e8-standards.txt"

ALCRY = 10**18
TERM_DAYS = 365
GRACE_DAYS = 90
ZERO = "zero"

VECTORS_DIGEST = "8cb9da945b0eed8f4432d31b71d20fffb72a6317fc90204d1890bd480c062bd3"
SCENARIO_DIGEST = "17fd44850375c54c9cf9826b8ed55da0faf1855da72514184c83501f07409d71"
UI_HTML_SHA = "bf1486e2f6475ebaffdc473a75d4fbd39e303869c803269b63c64d1ec851167f"
SIM_LINE = (
    '{"vectors": 50, "vectors_ok": true, "first_vote": [1, 1, "yes"], '
    '"ui_votes": 4, "tally_yes": 250000, "tally_no": 75000, '
    '"tally_abstain": 25000, "state": "executed"}'
)

# ------------------------------------------------------------- model


class E8Error(Exception):
    pass


class Model:
    """Semantics mirror of crates/aura-storage/src/nft.rs."""

    def __init__(self) -> None:
        self.owner721: dict[int, str] = {}
        self.approved: dict[int, str] = {}
        self.bal721: dict[str, int] = {}
        self.supply721 = 0
        self.bal1155: dict[tuple[str, int], int] = {}
        self.supply1155: dict[int, int] = {}
        self.uri1155: dict[int, str] = {}
        self.operator: dict[tuple[str, str], bool] = {}
        self.names: dict[str, dict] = {}
        self.primary: dict[str, str] = {}
        self.identity: dict[str, str] = {}
        self.day = 0

    def mint721(self, by, to, id):
        if by != "root":
            raise E8Error(f"E8: not collection owner ({by})")
        if to == ZERO:
            raise E8Error("E8: zero address")
        if id in self.owner721:
            raise E8Error(f"E8: token already exists ({id})")
        self.owner721[id] = to
        self.bal721[to] = self.bal721.get(to, 0) + 1
        self.supply721 += 1

    def transfer721(self, by, id, to):
        if id not in self.owner721:
            raise E8Error(f"E8: token does not exist ({id})")
        if self.owner721[id] != by:
            raise E8Error(f"E8: not token owner ({by}/{id})")
        if to == ZERO:
            raise E8Error("E8: zero address")
        self.bal721[by] -= 1
        self.bal721[to] = self.bal721.get(to, 0) + 1
        self.owner721[id] = to
        self.approved.pop(id, None)

    def approve721(self, by, id, spender):
        if id not in self.owner721:
            raise E8Error(f"E8: token does not exist ({id})")
        if self.owner721[id] != by:
            raise E8Error(f"E8: not token owner ({by}/{id})")
        if spender == ZERO:
            raise E8Error("E8: zero address")
        self.approved[id] = spender

    def transfer_from721(self, by, id, to):
        if id not in self.owner721:
            raise E8Error(f"E8: token does not exist ({id})")
        if to == ZERO:
            raise E8Error("E8: zero address")
        if self.approved.get(id) != by:
            raise E8Error(f"E8: not approved ({by}/{id})")
        frm = self.owner721[id]
        self.bal721[frm] -= 1
        self.bal721[to] = self.bal721.get(to, 0) + 1
        self.owner721[id] = to
        self.approved.pop(id, None)

    def burn721(self, by, id):
        if id not in self.owner721:
            raise E8Error(f"E8: token does not exist ({id})")
        if self.owner721[id] != by:
            raise E8Error(f"E8: not token owner ({by}/{id})")
        del self.owner721[id]
        self.approved.pop(id, None)
        self.bal721[by] -= 1
        self.supply721 -= 1

    def read_owner_of(self, id):
        if id not in self.owner721:
            raise E8Error(f"E8: token does not exist ({id})")

    def mint1155(self, by, to, id, amount):
        if by != "root":
            raise E8Error(f"E8: not collection owner ({by})")
        if to == ZERO:
            raise E8Error("E8: zero address")
        if amount == 0:
            raise E8Error("E8: amount must be positive")
        self.bal1155[(to, id)] = self.bal1155.get((to, id), 0) + amount
        self.supply1155[id] = self.supply1155.get(id, 0) + amount

    def transfer1155(self, frm, by, id, to, amount):
        if to == ZERO:
            raise E8Error("E8: zero address")
        if amount == 0:
            raise E8Error("E8: amount must be positive")
        if by != frm and not self.operator.get((frm, by), False):
            raise E8Error(f"E8: not approved ({by}/{id})")
        have = self.bal1155.get((frm, id), 0)
        if have < amount:
            raise E8Error(f"E8: insufficient balance ({frm}/{id}/{have}/{amount})")
        self.bal1155[(frm, id)] = have - amount
        self.bal1155[(to, id)] = self.bal1155.get((to, id), 0) + amount

    def set_operator(self, by, operator, approved):
        if operator == ZERO:
            raise E8Error("E8: zero address")
        self.operator[(by, operator)] = approved

    def transfer_batch1155(self, frm, by, to, ids, amounts):
        if len(ids) != len(amounts):
            raise E8Error(f"E8: batch length mismatch ({len(ids)}/{len(amounts)})")
        if to == ZERO:
            raise E8Error("E8: zero address")
        if by != frm and not self.operator.get((frm, by), False):
            raise E8Error(f"E8: not approved ({by}/{ids[0]})")
        for id, amount in zip(ids, amounts):
            if amount == 0:
                raise E8Error("E8: amount must be positive")
            have = self.bal1155.get((frm, id), 0)
            if have < amount:
                raise E8Error(f"E8: insufficient balance ({frm}/{id}/{have}/{amount})")
        for id, amount in zip(ids, amounts):
            self.bal1155[(frm, id)] -= amount
            self.bal1155[(to, id)] = self.bal1155.get((to, id), 0) + amount

    def set_uri(self, by, id, uri):
        if by != "root":
            raise E8Error(f"E8: not collection owner ({by})")
        self.uri1155[id] = uri

    @staticmethod
    def valid_name(name: str) -> bool:
        if not name.endswith(".aura") or len(name) == len(".aura"):
            return False
        label = name[: -len(".aura")]
        if not (1 <= len(label) <= 32):
            return False
        if not all(c.islower() or c.isdigit() or c == "-" for c in label):
            return False
        return label[0].isalnum() and label[-1].isalnum()

    def register_name(self, by, name, day):
        self.day = day
        if not self.valid_name(name):
            raise E8Error(f"E8: invalid name ({name})")
        if name in self.names and day <= self.names[name]["expiry"] + GRACE_DAYS:
            raise E8Error(f"E8: name already registered ({name})")
        self.names[name] = {"owner": by, "target": by, "expiry": day + TERM_DAYS}

    def renew_name(self, name, day):
        self.day = day
        if name not in self.names:
            raise E8Error(f"E8: name not registered ({name})")
        rec = self.names[name]
        rec["expiry"] = max(day, rec["expiry"]) + TERM_DAYS

    def transfer_name(self, by, name, to, day):
        self.day = day
        if name not in self.names:
            raise E8Error(f"E8: name not registered ({name})")
        rec = self.names[name]
        if day > rec["expiry"] + GRACE_DAYS:
            raise E8Error(f"E8: name expired ({name})")
        if rec["owner"] != by:
            raise E8Error(f"E8: not name owner ({by}/{name})")
        if to == ZERO:
            raise E8Error("E8: zero address")
        if self.primary.get(by) == name:
            del self.primary[by]
        rec["owner"] = to

    def set_target(self, by, name, target, day):
        self.day = day
        if name not in self.names:
            raise E8Error(f"E8: name not registered ({name})")
        rec = self.names[name]
        if day > rec["expiry"] + GRACE_DAYS:
            raise E8Error(f"E8: name expired ({name})")
        if rec["owner"] != by:
            raise E8Error(f"E8: not name owner ({by}/{name})")
        if target == ZERO:
            raise E8Error("E8: zero address")
        rec["target"] = target

    def resolve(self, name, day):
        self.day = day
        if name not in self.names:
            raise E8Error(f"E8: name not registered ({name})")
        rec = self.names[name]
        if day > rec["expiry"] + GRACE_DAYS:
            raise E8Error(f"E8: name expired ({name})")
        return rec["target"]

    def set_primary(self, by, name, day):
        self.day = day
        if name not in self.names:
            raise E8Error(f"E8: name not registered ({name})")
        rec = self.names[name]
        if day > rec["expiry"] + GRACE_DAYS:
            raise E8Error(f"E8: name expired ({name})")
        if rec["owner"] != by:
            raise E8Error(f"E8: not name owner ({by}/{name})")
        self.primary[by] = name

    def advance_day(self, day):
        self.day = day

    def set_identity(self, by, name, digest, day):
        self.day = day
        if name not in self.names:
            raise E8Error(f"E8: name not registered ({name})")
        rec = self.names[name]
        if day > rec["expiry"] + GRACE_DAYS:
            raise E8Error(f"E8: name expired ({name})")
        if rec["owner"] != by:
            raise E8Error(f"E8: not name owner ({by}/{name})")
        self.identity[name] = digest

    def clear_identity(self, by, name, day=None):
        if day is not None:
            self.day = day
        if name not in self.names:
            raise E8Error(f"E8: name not registered ({name})")
        if self.names[name]["owner"] != by:
            raise E8Error(f"E8: not name owner ({by}/{name})")
        self.identity.pop(name, None)

    def read_identity(self, name, day):
        self.day = day
        if name not in self.names:
            raise E8Error(f"E8: name not registered ({name})")
        if name not in self.identity:
            raise E8Error(f"E8: no identity record ({name})")
        return self.identity[name]

    # query(): the fixture read-key grammar.
    def query(self, key: str) -> str:
        head, _, rest = key.partition(":")
        if head == "owner_of":
            return self.owner721.get(int(rest), "none")
        if head == "approved":
            return self.approved.get(int(rest), "none")
        if head == "supply721":
            return str(self.supply721)
        if head == "balance721":
            return str(self.bal721.get(rest, 0))
        if head == "balance1155":
            who, _, id = rest.rpartition(":")
            return str(self.bal1155.get((who, int(id)), 0))
        if head == "supply1155":
            return str(self.supply1155.get(int(rest), 0))
        if head == "uri":
            return self.uri1155.get(int(rest), "none")
        if head == "resolve":
            try:
                return self.resolve(rest, self.day)
            except E8Error:
                return "none"
        if head == "name_owner":
            rec = self.names.get(rest)
            return rec["owner"] if rec else "none"
        if head == "expiry":
            rec = self.names.get(rest)
            return str(rec["expiry"]) if rec else "none"
        if head == "reverse":
            return self.primary.get(rest, "none")
        if head == "identity":
            try:
                return self.read_identity(rest, self.day)
            except E8Error:
                return "none"
        if head == "day":
            return str(self.day)
        if head == "operator":
            holder, _, op = rest.rpartition(":")
            return "true" if self.operator.get((holder, op), False) else "false"
        raise AssertionError(f"unknown read key: {key}")


