def build_baseline_fixture() -> str:
    res = subprocess.run(
        [
            "cargo",
            "run",
            "--quiet",
            "-p",
            "aura-wallet",
            "--bin",
            "aura-wallet",
            "--",
            "report",
            "--fixture",
            "--workspace",
            str(REPO),
        ],
        cwd=REPO,
        capture_output=True,
        text=True,
        check=True,
    )
    return res.stdout


