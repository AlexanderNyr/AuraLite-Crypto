#!/usr/bin/env python3
"""Generate S0 baseline golden vectors from an INDEPENDENT Python model.

No Rust code, no network. This script models the deliberately naive S0
in-memory state (an append-only write log with last-write-wins lookup), emits
canonical write-log bytes, final-view bytes and the measured insertion-order
defect for four scenarios.

Usage:
    python3 tools/gen_s0_vectors.py
    make gen-s0-vectors

Output: crates/aura-state/tests/fixtures/s0_golden.txt
"""

from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "crates" / "aura-state" / "tests" / "fixtures" / "s0_golden.txt"

FINAL_VIEW_CONTEXT = b"AuraLite-Crypto/s0-final-view-v1\x00"
KEY_PREFIX = b"\x01"  # C7 KeySpace::Account


def varint(value: int) -> bytes:
    out = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        out.append(byte | (0x80 if value else 0))
        if not value:
            return bytes(out)


def u64(value: int) -> bytes:
    return value.to_bytes(8, "little")


def u128(value: int) -> bytes:
    return value.to_bytes(16, "little")


def account_key(index: int) -> bytes:
    # 0x01 || 20 address bytes — matches C7 StateKey::account raw layout.
    return KEY_PREFIX + bytes([index] * 20)


def encode_key(key: bytes) -> bytes:
    return varint(len(key)) + key


def write_log_bytes(writes: list[tuple[bytes, int, int]]) -> bytes:
    out = bytearray(varint(len(writes)))
    for key, nonce, balance in writes:
        out += encode_key(key) + u64(nonce) + u128(balance)
    return bytes(out)


def final_view(writes: list[tuple[bytes, int, int]]) -> dict[bytes, tuple[int, int]]:
    view: dict[bytes, tuple[int, int]] = {}
    for key, nonce, balance in writes:
        view[key] = (nonce, balance)  # last write wins — order dependent
    return view


def final_view_bytes(writes: list[tuple[bytes, int, int]]) -> bytes:
    view = final_view(writes)
    out = bytearray(FINAL_VIEW_CONTEXT)
    out += varint(len(view))
    for key in sorted(view):
        nonce, balance = view[key]
        out += encode_key(key) + u64(nonce) + u128(balance)
    return bytes(out)


W = lambda k, n, b: (account_key(k), n, b)  # noqa: E731

SCENARIOS: list[list[tuple[bytes, int, int]]] = [
    # 1. Three conflicting writes to one account.
    [W(1, 0, 100), W(1, 0, 200), W(1, 0, 300)],
    # 2. Interleaved writes to two accounts.
    [W(1, 1, 10), W(2, 2, 20), W(1, 3, 30), W(2, 4, 40)],
    # 3. Disjoint keys: the same set in a different order gives the SAME view.
    [W(1, 0, 11), W(2, 0, 22), W(3, 0, 33)],
    # 4. Boundary values (u64/u128 maxima) on one account.
    [W(1, 0, 2**128 - 1), W(1, 0, 0), W(1, 0, 1), W(1, 0, 2**64), W(1, 0, 2**128 - 2)],
]


def main() -> int:
    lines = [
        "# AuraLite-Crypto S0 state-baseline golden vectors",
        "# Generated by tools/gen_s0_vectors.py (independent Python model).",
        "# S0 is DELIBERATELY naive: an append-only write log whose lookup",
        "# returns the last write. The order dependence is a MEASURED DEFECT",
        "# that S1 must remove with a deterministic versioned Merkle tree.",
        "# Format: key=value (hex or decimal). Do not edit by hand.",
        f"final_view_context={FINAL_VIEW_CONTEXT.hex()}",
        "no_root=1",
        "no_persistence=1",
        "deterministic=0",
        f"scenario_count={len(SCENARIOS)}",
        "report_scenario=1",
        "report_writes=3",
        "report_accounts=1",
        "report_has_root=0",
        "report_has_persistence=0",
        "report_deterministic=0",
    ]

    defect_found = False
    for index, order_a in enumerate(SCENARIOS, 1):
        order_b = list(reversed(order_a))
        log_a, log_b = write_log_bytes(order_a), write_log_bytes(order_b)
        view_a, view_b = final_view_bytes(order_a), final_view_bytes(order_b)
        defect = int(view_a != view_b)
        defect_found |= bool(defect)
        p = lambda k: f"scenario_{index}_{k}"  # noqa: E731
        lines += [
            f"{p('writes_a')}={log_a.hex()}",
            f"{p('writes_b')}={log_b.hex()}",
            f"{p('final_a')}={view_a.hex()}",
            f"{p('final_b')}={view_b.hex()}",
            f"{p('defect')}={defect}",
            f"{p('writes_count')}={len(order_a)}",
            f"{p('accounts_a')}={len(final_view(order_a))}",
            f"{p('accounts_b')}={len(final_view(order_b))}",
            f"{p('balance_key1_a')}={final_view(order_a)[account_key(1)][1]}",
            f"{p('balance_key1_b')}={final_view(order_b)[account_key(1)][1]}",
        ]

    if not defect_found:
        raise SystemExit("self-check failed: no scenario exposes the insertion-order defect")
    if final_view_bytes(SCENARIOS[2]) != final_view_bytes(list(reversed(SCENARIOS[2]))):
        raise SystemExit("self-check failed: disjoint-key scenario must be order independent")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(lines)} lines)")
    print(f"  scenarios: {len(SCENARIOS)}, defect exposed: {defect_found}")
    print("  self-check: conflicting writes diverge; disjoint writes do not")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
