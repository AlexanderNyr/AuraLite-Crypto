#!/usr/bin/env python3
"""Record the C9 dependency delta against all existing allowlist files.

C3 baseline is frozen; C8 and later phases add reviewed addenda. This tool
computes `current Cargo.lock external set` minus `union(baseline, addenda)`
and writes `docs/spec/c9-dependency-addendum.txt`.

Usage:
    python3 tools/record_c9_deps.py
    make record-c9-deps
"""

from __future__ import annotations

import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LOCK = REPO / "Cargo.lock"
SPEC = REPO / "docs" / "spec"
OUT = SPEC / "c9-dependency-addendum.txt"

HEADER = [
    "# AuraLite-Crypto external dependency addendum (C9).",
    "# Generated by tools/record_c9_deps.py from Cargo.lock.",
    "# C9 added proptest as a DEV dependency of aura-testkit only, with",
    "# default features disabled (no fork/timeout). These crates never enter",
    "# the node binary or the consensus path.",
    "# The C3 baseline and C8 addendum are historical evidence (checksummed);",
    "# this file records ONLY the crates added after them.",
]


def read_pairs(path: Path) -> set[tuple[str, str]]:
    result = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, version = line.split("=", 1)
        result.add((name, version))
    return result


def main() -> int:
    data = tomllib.loads(LOCK.read_text(encoding="utf-8"))
    current = {
        (package["name"], package["version"])
        for package in data.get("package", [])
        if "source" in package
    }
    known = read_pairs(SPEC / "c3-dependency-allowlist.txt")
    for path in SPEC.glob("*-dependency-addendum.txt"):
        if path != OUT:
            known |= read_pairs(path)

    removed = sorted(known - current)
    if removed:
        print(f"ERROR: previously allowlisted crates disappeared: {removed}")
        return 1
    added = sorted(current - known)
    OUT.write_text(
        "\n".join(HEADER + [f"{name}={version}" for name, version in added]) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(REPO)} ({len(added)} crates added since C8)")
    for name, version in added:
        print(f"  + {name}={version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
