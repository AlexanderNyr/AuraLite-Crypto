#!/usr/bin/env python3
"""Write W7 evidence (`docs/evidence/w7/`).

Reproducible bundle for the W7 gate ("genesis ceremony never writes one
private key outside shredded media; NC: no_private_key_in_outputs"): captures
the 10-scenario ceremony suite, `tools/nc_w7.py` (the mutation controls), and
inventories the pinned fixtures against the independent generator. Model:
tools/write_w6_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "w7"
FIXTURE = ROOT / "crates/aura-genesis/tests/fixtures/w7_ceremony_vectors.json"
GENERATOR = ROOT / "tools/gen_w7_vectors.py"
RUNNER = ROOT / "crates/aura-genesis/tests/w7_ceremony.rs"
CEREMONY = ROOT / "crates/aura-genesis/src/ceremony.rs"
NAMED = "no_private_key_in_outputs"
TOTAL_NC = 668  # 662 through W6 + 6 W7 controls


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    test_log = run(["cargo", "test", "-p", "aura-genesis", "--test", "w7_ceremony"])
    (EVIDENCE / "test-w7.log").write_text(test_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_w7.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    cases = doc["cases"]
    named_found = any(
        c["name"] == NAMED
        and c.get("nc_ref") == 1
        and c["exit"] == 0
        and "verify=ok" in c["stdout"]
        and "scan=clean" in c["stdout"]
        for c in cases
    )
    inv = [
        "# W7 inventory (generated by tools/write_w7_evidence.py)",
        f"gate={doc['gate']}",
        f"vectors={len(cases)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"fixtures_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"runner_sha256={sha256(RUNNER)}",
        "cases:",
    ]
    inv += [f"  {c['name']} exit={c['exit']} nc={c.get('nc_ref', '-')}" for c in cases]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls cumulative")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    report = f"""# W7 closeout report — offline genesis ceremony (the O5 gate)

Date: 2026-11-25. Gate (WALLET_PLAN row W7): "genesis ceremony never writes
one private key outside shredded media; NC: {NAMED}" — **satisfied**.

- **The gate**: `{NAMED}` (the named control) runs the full ceremony
  (open, generate, split, shred) and then `verify --root .`: the scanner
  flags any `media/` file or `secret=` line and must report `scan=clean`;
  mutation NC-1 (`tools/nc_w7.py`) skips shredding and the case must turn
  red. "Not one private key in the repository/CI" — the O5 DoD.
- **Scenarios**: 10 deterministic cases from the independent oracle
  `tools/gen_w7_vectors.py` (BLAKE3 via gen_c8, Ed25519 RFC 8032 via gen_c4,
  gen_c8 genesis canonical bytes/hash/validator_set_hash), asserted
  byte-for-byte by `tests/w7_ceremony.rs` (11/11 with the count guard).
  Groups: sealing trajectory (1), pubkey-set binding (1), private-material
  scan (1), Shamir sharing (3), witness chain (2), ceremony ordering (2).
- **Mutation controls**: 6/6 PASS (shredding skipped, threshold check
  dropped, witness chain check dropped, pubkey-set binding dropped,
  reconstruction corrupted, media-present check dropped).
- **Device model** (docs/w7-genesis-ceremony-plan.md): D-W7-1 deterministic
  offline key derivation (BLAKE3(KEY_CONTEXT || entropy || i), Ed25519),
  D-W7-2 Shamir GF(2^8) sharing with deterministic coefficients and
  Lagrange-at-0 reconstruction, D-W7-3 the hash-chained witness log
  (`witness chain broken` / `witness log incomplete`), D-W7-4 destruction of
  temporary media (double overwrite + remove; seal refuses while media
  exists), D-W7-5 the sealed genesis commits to exactly the witnessed pubkey
  set (`validator set mismatch`).
- **Reproducibility**: the whole ceremony runs from two inputs only
  (`params`, `entropy`); the fixture pins the full trajectory, the genesis
  hash `15d321f9…` and validator-set hash `70f63791…` are BLAKE3
  commitments computed independently in Python and Rust.

Receipts: `gates.txt`, `test-w7.log`, `nc.log`, `inventory.txt`,
`SHA256SUMS`. Regenerate with `make evidence-w7`. Public test data only —
never use for real validator keys.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    gates = [
        "# W7 gates",
        "ceremony gate + 10 scenarios: PASS (11 tests: 10 scenarios + count guard)"
        if "test result: ok. 11 passed" in test_log
        else "ceremony gate + 10 scenarios: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)"
        if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [FIXTURE, GENERATOR, RUNNER, CEREMONY,
                  ROOT / "tools/nc_w7.py",
                  EVIDENCE / "test-w7.log", EVIDENCE / "nc.log",
                  EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                  EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# W7 evidence — offline genesis ceremony (10 scenarios)

Gate (WALLET_PLAN row W7): "genesis ceremony never writes one private key
outside shredded media; NC: {NAMED}". All fixtures are PUBLIC TEST DATA ONLY
— never use for real validator keys.

- `test-w7.log` — `cargo test -p aura-genesis --test w7_ceremony`:
  {len(cases)} scenarios plus `vectors_file_has_exactly_10_unique_cases`,
  byte-for-byte against the independent oracle.
- `nc.log` — `tools/nc_w7.py` mutation controls (6): each source mutation must
  turn its named test red; compilation failure is not a valid red.
- `inventory.txt` — the 10 cases with exit codes and NC refs, the named
  control, the cumulative NC total ({TOTAL_NC}) and SHA-256 pins of fixture,
  generator, runner.
- `report.md`, `gates.txt` — closeout report and gate summary.
- `SHA256SUMS` — digests of the deliverables and evidence files.

The vectors are produced by `tools/gen_w7_vectors.py` (pure Python: BLAKE3,
Ed25519 RFC 8032, Shamir GF(2^8), gen_c8 genesis primitives). Regenerate with
`make gen-w7-vectors`; rebuild this bundle with `make evidence-w7`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} ({len(cases)} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
