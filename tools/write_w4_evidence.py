#!/usr/bin/env python3
"""Write W4 evidence (`docs/evidence/w4/`).

Reproducible bundle for the W4 gate ("3-of-5: 3 collected -> success, 2 ->
reject; NC: threshold bypass -> red"): captures `make test-w4` (the 22-vector
suite), `tools/nc_w4.py` (the mutation controls), and inventories the pinned
fixture against the independent generator. Model:
tools/write_w3_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "w4"
FIXTURE = ROOT / "crates/aura-wallet/tests/fixtures/w4_multisig_vectors.json"
GENERATOR = ROOT / "tools/gen_w4_vectors.py"
RUNNER = ROOT / "crates/aura-wallet/tests/w4_multisig.rs"
NAMED = "collect_2_of_5_rejected"
TOTAL_NC = 424  # 418 through W3 + 6 W4 controls


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    test_log = run(["cargo", "test", "-p", "aura-wallet", "--features",
                    "insecure-test-kdf", "--test", "w4_multisig"])
    (EVIDENCE / "test-w4.log").write_text(test_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_w4.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    cases = doc["cases"]
    named_found = any(
        c["name"] == NAMED
        and c["expect_exit"] == 65
        and any("threshold not met (2/3)" in line for line in c["expect_stderr"])
        for c in cases
    )
    inv = [
        "# W4 inventory (generated by tools/write_w4_evidence.py)",
        f"gate={doc['gate']}",
        f"vectors={len(cases)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"fixtures_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"runner_sha256={sha256(RUNNER)}",
        "cases:",
    ]
    inv += [f"  {c['name']} exit={c['expect_exit']}" for c in cases]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    report = f"""# W4 closeout report — wallet-level M-of-N multisig contract

Date: 2026-11-11. Gate (WALLET_PLAN row W4): "3-of-5: 3 collected -> success,
2 -> reject; NC: threshold bypass -> red" — **satisfied**.

- **Threshold gate**: `collect_3_of_5_passed` (3 approvals of 5 -> exit 0,
  `signatures=3/threshold=3`) and the named control `collect_2_of_5_rejected`
  (2 approvals -> `error: multisig: threshold not met (2/3)`, exit 65).
  Mutation NC-1 (`tools/nc_w4.py`) bypasses the threshold check and requires
  that test to go red.
- **Vectors**: 22 deterministic cases from the independent oracle
  `tools/gen_w4_vectors.py` (canonical descriptor/proposal/approval bytes,
  BLAKE3, Ed25519 RFC 8032-checked, `contract` domain), asserted
  byte-for-byte by `tests/w4_multisig.rs` (23/23 with the count guard).
  Groups: init (4), propose (5), approve (4), collect (7), rotation/e2e (2).
- **Mutation controls**: 6/6 PASS (threshold bypassed, signature verification
  skipped, duplicate approvals accepted, membership dropped, expiry dropped,
  proposal binding dropped).
- **Contract model** (docs/w4-multisig-plan.md): D-W4-1 canonical documents
  (contract id = BLAKE3 of the descriptor bytes), D-W4-2 the fixed AuraLite
  `contract` signature domain, D-W4-3 member rotation as a `rotate` proposal
  under the old membership, D-W4-4 deterministic `--height` timeouts with the
  fixed refusal set.
- **Cross-check pin**: the 3-of-5 contract over the W1 smoke keys
  (accounts 0..4, timeout 1000) has id
  `a3ed446e112c368e49e44553e7fbc288a6e8fc3c75bc35b508d08ab1e2ff9eb6` in both
  the Rust implementation and the Python oracle.

Receipts: `gates.txt`, `test-w4.log`, `nc.log`, `inventory.txt`, `SHA256SUMS`.
Regenerate with `make evidence-w4`. Public test data only — never use for funds.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    gates = [
        "# W4 gates",
        "3-of-5 gate + 22 vectors: PASS (23 tests: 22 vectors + count guard)"
        if "test result: ok. 23 passed" in test_log
        else "3-of-5 gate + 22 vectors: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)" if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [FIXTURE, GENERATOR, RUNNER,
                  ROOT / "tools/nc_w4.py", ROOT / "crates/aura-wallet/src/multisig.rs",
                  EVIDENCE / "test-w4.log", EVIDENCE / "nc.log",
                  EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                  EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# W4 evidence — M-of-N multisig contract (22 CLI vectors)

Gate (WALLET_PLAN row W4): "3-of-5: 3 collected -> success, 2 -> reject; NC:
threshold bypass -> red". All fixtures are PUBLIC TEST DATA ONLY — never use
for funds.

- `test-w4.log` — `cargo test --features insecure-test-kdf --test w4_multisig`:
  {len(cases)} vectors plus `vectors_file_has_exactly_22_unique_cases`,
  byte-for-byte against the independent oracle.
- `nc.log` — `tools/nc_w4.py` mutation controls (6): each source mutation must
  turn its named test red; compilation failure is not a valid red.
- `inventory.txt` — the 22 cases with exit codes, the named control, the
  cumulative NC total ({TOTAL_NC}) and SHA-256 pins of fixture, generator, runner.
- `report.md`, `gates.txt` — closeout report and gate summary.
- `SHA256SUMS` — digests of the deliverables and evidence files.

The vectors are produced by `tools/gen_w4_vectors.py` (pure Python: BLAKE3,
Ed25519 RFC 8032, domain_message, BIP-39/SLIP-0010, bech32). Regenerate with
`make gen-w4-vectors`; rebuild this bundle with `make evidence-w4`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} ({len(cases)} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
