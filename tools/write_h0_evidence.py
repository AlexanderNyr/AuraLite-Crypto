#!/usr/bin/env python3
"""Write H0 evidence (`docs/evidence/h0/`).

Reproducible bundle for the H0 gate ("scenario without an owner -> red"):
captures `make check-h0` (the threat-model review gate over 32 scenarios),
`tools/nc_h0.py` (the mutation controls), and inventories the pinned oracle
output against the document. Model: tools/write_w4_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "h0"
DOC = ROOT / "docs" / "THREAT_MODEL.md"
FIXTURE = ROOT / "tools" / "fixtures" / "h0_threat_model_vectors.json"
GENERATOR = ROOT / "tools" / "gen_h0_vectors.py"
GATE = ROOT / "tools" / "check_threat_model.py"
NAMED = "scenario_without_an_owner"
TOTAL_NC = 430  # 424 through W4 + 6 H0 controls


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    check_log = run([sys.executable, "tools/check_threat_model.py"])
    (EVIDENCE / "check.log").write_text(check_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_h0.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    scenarios = doc["scenarios"]
    named_found = any(
        s["id"] == "H0-S07" and s.get("owner") for s in scenarios
    )
    inv = [
        "# H0 inventory (generated by tools/write_h0_evidence.py)",
        f"gate={doc['format']}",
        f"scenarios={len(scenarios)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"doc_sha256={sha256(DOC)}",
        f"fixture_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"gate_tool_sha256={sha256(GATE)}",
        "owners:",
    ]
    owners: dict[str, int] = {}
    for s in scenarios:
        owners[s["owner"]] = owners.get(s["owner"], 0) + 1
    inv += [f"  {name}: {n}" for name, n in sorted(owners.items())]
    inv.append("scenarios:")
    inv += [f"  {s['id']} owner={s['owner']} class={s['class']}" for s in scenarios]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    report = f"""# H0 closeout report — threat model with owned scenarios

Date: 2026-11-11. Gate (SECURITY_PLAN row H0): "scenario without an owner ->
red" over `docs/THREAT_MODEL.md` (assets, adversaries, trust boundaries, 30+
scenarios) — **satisfied**.

- **Review gate**: `tools/check_threat_model.py` parses the threat model and
  enforces: at least 30 scenarios, unique ids, the required fields (class,
  boundary, assets, entry, impact, owner, mitigations), known
  class/boundary/asset references, owners drawn from the seven roles, and
  non-empty mitigations. Result: `THREAT MODEL: OK — {len(scenarios)}
  scenarios, all owned`.
- **Named control** ({NAMED}): `tools/nc_h0.py` NC-1 deletes one Owner field
  (H0-S07) and requires the gate to fail with
  `error: scenario H0-S07: missing owner`.
- **Vectors**: the deterministic oracle `tools/gen_h0_vectors.py` extracts the
  scenario inventory into `tools/fixtures/h0_threat_model_vectors.json`
  (AURALITE-THREAT-VECTORS-V1); the gate re-derives the records with its own
  parser and compares field-by-field (byte-for-byte property).
- **Mutation controls**: 6/6 PASS (owner dropped, duplicate id, unknown class,
  unknown boundary, empty mitigations, fewer than 30 scenarios).
- **Content**: {len(scenarios)} scenarios H0-S01..H0-S32 across the five
  adversary classes (external, validator, insider, supply chain, physical)
  and six trust boundaries, each mapped to shipped mitigations (W0–W4, B/N/D
  phases) and residual risk; unowned scenarios cannot exist by construction.

Receipts: `gates.txt`, `check.log`, `nc.log`, `inventory.txt`, `SHA256SUMS`.
Regenerate with `make evidence-h0`. Public project material only.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    gates = [
        "# H0 gates",
        f"threat model review gate: PASS ({len(scenarios)} scenarios, all owned)"
        if "THREAT MODEL: OK" in check_log else "threat model review gate: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)" if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [DOC, FIXTURE, GENERATOR, GATE,
                  ROOT / "tools" / "nc_h0.py",
                  EVIDENCE / "check.log", EVIDENCE / "nc.log",
                  EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                  EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# H0 evidence — threat model review gate ({len(scenarios)} owned scenarios)

Gate (SECURITY_PLAN row H0): "scenario without an owner -> red".

- `check.log` — `tools/check_threat_model.py`: parses `docs/THREAT_MODEL.md`,
  enforces the schema (30+ scenarios, owners, references, mitigations) and
  compares against the pinned oracle output.
- `nc.log` — `tools/nc_h0.py` mutation controls (6): each document mutation
  must turn the gate red with its specific `error:` line.
- `inventory.txt` — the {len(scenarios)} scenarios with owner/class, the named
  control, the cumulative NC total ({TOTAL_NC}) and SHA-256 pins of document,
  fixture, generator and gate tool.
- `report.md`, `gates.txt` — closeout report and gate summary.
- `SHA256SUMS` — digests of the deliverables and evidence files.

The vectors are produced by `tools/gen_h0_vectors.py` (regenerate with
`make gen-h0-vectors` after editing the threat model); rebuild this bundle
with `make evidence-h0`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} ({len(scenarios)} scenarios)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
