#!/usr/bin/env python3
"""Public, independent Python reference for W1 canonical associated-data bytes.

No KDF, secret, encryption, or authentication is performed. The edge-case
address is intentionally invalid account metadata; it exercises JSON encoding
before authentication. Run without arguments to verify the committed vectors;
use --write only when deliberately reviewing and updating these public vectors.
"""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "crates/aura-wallet/tests/fixtures"
OUT = FIXTURES / "w1_aad_reference.json"


def reverse_objects(value):
    if isinstance(value, dict):
        return {key: reverse_objects(value[key]) for key in reversed(list(value))}
    if isinstance(value, list):
        return [reverse_objects(item) for item in value]
    return value


def generate():
    output = []
    for name, source in (
        ("argon2id-public", "w1_interop_argon2id.json"),
        ("scrypt-public", "w1_interop_scrypt.json"),
        ("string-escaping-unauthenticated", "w1_interop_argon2id.json"),
    ):
        doc = json.loads((FIXTURES / source).read_text(encoding="utf-8"))
        if name == "string-escaping-unauthenticated":
            # Legal as a nonempty unauthenticated input string, but never a
            # valid derived address. Covers control escapes, slash, quote,
            # backslash and non-ASCII UTF-8 including a supplementary scalar.
            doc["accounts"][0]["address"] = 'x\x00\x01\b\t\n\f\r\x1f/"\\é\u2028🔐'
        doc = reverse_objects(doc)
        header = {key: value for key, value in doc.items() if key != "ciphertext"}
        aad = json.dumps(header, sort_keys=True, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
        output.append({"name": name, "document": doc, "aad_hex": aad.hex(), "aad_sha256": hashlib.sha256(aad).hexdigest()})
    return (json.dumps(output, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def main():
    if sys.argv[1:] == ["--write"]:
        OUT.write_bytes(generate())
        print(f"WROTE public AAD vectors: {OUT}")
        return 0
    if sys.argv[1:]:
        print("usage: python3 tools/w1_aad_reference.py [--write]", file=sys.stderr)
        return 2
    if not OUT.is_file() or OUT.read_bytes() != generate():
        print("FAIL public AAD reference vectors differ from independently regenerated bytes", file=sys.stderr)
        return 1
    print("PASS independent Python W1 associated-data reference vectors (3 public cases)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
