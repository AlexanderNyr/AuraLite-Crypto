#!/usr/bin/env python3
"""Generate C9 golden vectors for the test rig (INDEPENDENT Python).

No Rust code, no network. Uses a deterministic LCG and a Python
transcription of the C2 minimal-LEB128 varint / `Vec<u8>` encoding.

Emits 512 vectors:
  * 128 valid varints (`value:minimal_encoding`) with boundary values;
  * 128 non-minimal or overflowing varints that must be rejected;
  * 128 encodings with trailing bytes that must be rejected;
  * 128 truncated encodings that must be rejected.

Usage:
    python3 tools/gen_c9_vectors.py
    make gen-c9-vectors

Output: crates/aura-testkit/tests/fixtures/c9_vectors.txt
"""

from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "crates" / "aura-testkit" / "tests" / "fixtures" / "c9_vectors.txt"

COUNT = 128
SEED = 0xA17A_11CE_C0DE_2026
MASK64 = (1 << 64) - 1


class Lcg:
    def __init__(self, seed: int) -> None:
        self.state = seed & MASK64

    def next(self) -> int:
        self.state = (self.state * 6364136223846793005 + 1442695040888963407) & MASK64
        return self.state

    def below(self, bound: int) -> int:
        return self.next() % bound


def varint(value: int) -> bytes:
    out = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        out.append(byte | (0x80 if value else 0))
        if not value:
            return bytes(out)


def decode_varint(data: bytes) -> tuple[int, int]:
    value = 0
    for index, byte in enumerate(data[:10]):
        value |= (byte & 0x7F) << (7 * index)
        if byte & 0x80 == 0:
            if byte == 0 and index > 0:
                raise ValueError("non-minimal")
            return value, index + 1
    raise ValueError("overflow or unterminated")


def main() -> int:
    rng = Lcg(SEED)
    lines = [
        "# AuraLite-Crypto C9 test-rig golden vectors",
        "# Generated by tools/gen_c9_vectors.py (independent Python, LCG seed fixed).",
        "# 512 vectors: 128 varint_ok, 128 varint_bad, 128 trailing, 128 truncated.",
        "# Format: key=value; varint_ok value is '<u64 BE hex>:<minimal LEB128 hex>'.",
        f"seed={SEED}",
        f"count={COUNT}",
    ]

    # 128 valid varints, including every interesting boundary.
    boundaries = [
        0, 1, 2, 3, 127, 128, 129, 255, 256, 257, 16383, 16384, 16385,
        2**31 - 1, 2**31, 2**32 - 1, 2**32, 2**63 - 1, 2**63, 2**64 - 1,
    ]
    values = boundaries + [rng.next() for _ in range(COUNT - len(boundaries))]
    assert len(values) == COUNT and len(set(values)) == COUNT
    for index, value in enumerate(values):
        encoded = varint(value)
        decoded, consumed = decode_varint(encoded)
        if decoded != value or consumed != len(encoded):
            raise SystemExit(f"varint self-check failed at {index}")
        lines.append(f"varint_ok_{index}={value:016x}:{encoded.hex()}")

    # 128 bad varints: non-minimal tail byte and/or >10-byte overflow.
    for index in range(COUNT):
        if index % 2 == 0:
            value = rng.next()
            encoded = varint(value)
            # Force a continuation on the final byte, append a zero terminator.
            bad = encoded[:-1] + bytes([encoded[-1] | 0x80]) + b"\x00"
        else:
            # 11 continuation bytes (never terminates within 10 bytes).
            bad = bytes([0x80 | rng.below(0x80) for _ in range(11)])
        try:
            decode_varint(bad)
        except ValueError:
            pass
        else:
            raise SystemExit(f"bad varint {index} was accepted by the reference")
        lines.append(f"varint_bad_{index}={bad.hex()}")

    # 128 trailing-byte vectors: a valid Vec<u8> encoding plus 1..128 extras.
    base = varint(3) + bytes([1, 2, 3])
    for index in range(COUNT):
        extra = bytes(rng.below(256) for _ in range(index + 1))
        lines.append(f"trailing_{index}={(base + extra).hex()}")

    # 128 truncated vectors: a valid 256-byte Vec<u8> encoding cut short.
    # A long payload guarantees 128 DISTINCT cut lengths, all shorter than
    # the declared length, so every one must hit unexpected EOF.
    long_payload = bytes(rng.below(256) for _ in range(256))
    full = varint(len(long_payload)) + long_payload
    for index in range(COUNT):
        cut = full[: len(full) - (index + 1)]
        assert len(cut) < len(full)
        lines.append(f"truncated_{index}={cut.hex()}")

    vectors = COUNT * 4
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(lines)} lines, {vectors} vectors)")
    print("  self-check: all valid varints round-trip; all bad varints rejected")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
