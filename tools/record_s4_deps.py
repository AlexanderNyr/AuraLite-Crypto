#!/usr/bin/env python3
"""Record the S4 dependency delta (none — sha2 is already in Cargo.lock).

The C3 baseline is frozen historical evidence. S4 adds no NEW external crate:
`sha2 = 0.10.9` was already in Cargo.lock via `k256` and is already listed in
`docs/spec/c3-dependency-allowlist.txt`. S4 only makes it a DIRECT dependency
of `aura-state` (for SHA-256 manifest and chunk digests). This file records that
fact so `tools/check_deps.py` sees a reviewed, explicit decision.

Usage:
    python3 tools/record_s4_deps.py
    make record-s4-deps
"""
from __future__ import annotations

import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "evidence" / "s4-dependency-addendum.txt"


def read_pairs(path: Path) -> set[tuple[str, str]]:
    out = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            name, version = line.split("=", 1)
            out.add((name, version))
    return out


def main() -> int:
    data = tomllib.loads((REPO / "Cargo.lock").read_text(encoding="utf-8"))
    current = {
        (p["name"], p["version"])
        for p in data.get("package", [])
        if "source" in p
    }
    known = read_pairs(REPO / "docs" / "spec" / "c3-dependency-allowlist.txt")
    for path in (REPO / "docs" / "spec").glob("*-dependency-addendum.txt"):
        known |= read_pairs(path)
    for path in (REPO / "docs" / "evidence").glob("*-dependency-addendum.txt"):
        if path != OUT:
            known |= read_pairs(path)
    missing = sorted(current - known)
    if missing:
        print(f"ERROR: unrecorded crates: {missing}")
        return 1
    if ("sha2", "0.10.9") not in current:
        print("ERROR: sha2=0.10.9 missing from Cargo.lock")
        return 1
    OUT.write_text(
        "\n".join([
            "# AuraLite-Crypto external dependency addendum (S4).",
            "# Generated by tools/record_s4_deps.py from Cargo.lock.",
            "# S4 adds NO new external crate: sha2=0.10.9 was already in the",
            "# lock via k256 and is already in the frozen C3 baseline.",
            "# S4 only makes it a DIRECT dependency of aura-state, for the",
            "# SHA-256 manifest checksum and per-chunk digests.",
            "# No crate lines below — the resolved external set is unchanged.",
        ]) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(REPO)} (0 new crates)")
    print("  sha2=0.10.9 promoted to direct dependency of aura-state")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
