#!/usr/bin/env python3
"""Generate C2 golden vectors from an INDEPENDENT codec implementation.

This is a standalone transcription of the AuraLite-Crypto canonical wire
format. It does not import the Rust crate. The Rust tests in
`crates/aura-codec/tests/c2_codec.rs` must reproduce these exact bytes.

Wire format (all integers little-endian unless noted):
    version   : u8 (CODEC_VERSION = 1)
    domain    : u8 tag (Tx=0, Vote=1, Block=2, Contract=3, Genesis=4)
    flag      : u8 bool (0 or 1 only)
    chain_id  : varint byte-length + UTF-8 bytes
    height    : u64
    nonce     : u64
    amount    : u128
    hash      : 32 raw bytes
    address   : 20 raw bytes
    memo      : u8 tag (0=None, 1=Some) + optional (varint len + UTF-8)
    tags      : varint count + repeated (varint keylen + UTF-8 key, u64 value)
                in STRICTLY ascending key order

varint = minimal unsigned LEB128. Non-minimal encodings are not generated
here except deliberately in the `bad_*` vectors.

Usage:
    python3 tools/gen_c2_vectors.py
    make gen-c2-vectors

Output: crates/aura-codec/tests/fixtures/c2_golden.txt
"""

from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "crates" / "aura-codec" / "tests" / "fixtures" / "c2_golden.txt"

CODEC_VERSION = 1
MAX_LENGTH = 1 << 20
DOMAIN_TAGS = {"tx": 0, "vote": 1, "block": 2, "contract": 3, "genesis": 4}


def varint(value: int) -> bytes:
    out = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        if value == 0:
            out.append(byte)
            return bytes(out)
        out.append(byte | 0x80)


def u8(value: int) -> bytes:
    return value.to_bytes(1, "little")


def u64(value: int) -> bytes:
    return value.to_bytes(8, "little")


def u128(value: int) -> bytes:
    return value.to_bytes(16, "little")


def text(value: str) -> bytes:
    raw = value.encode("utf-8")
    return varint(len(raw)) + raw


def memo(value: str | None) -> bytes:
    return b"\x00" if value is None else b"\x01" + text(value)


def tags(items: dict[str, int]) -> bytes:
    out = bytearray(varint(len(items)))
    for key in sorted(items):
        out += text(key) + u64(items[key])
    return bytes(out)


def record(
    chain: str,
    domain: str,
    flag: bool,
    height: int,
    nonce: int,
    amount: int,
    hash_bytes: bytes,
    address_bytes: bytes,
    memo_value: str | None,
    tag_items: dict[str, int],
) -> bytes:
    assert len(hash_bytes) == 32 and len(address_bytes) == 20
    return b"".join(
        [
            u8(CODEC_VERSION),
            u8(DOMAIN_TAGS[domain]),
            u8(1 if flag else 0),
            text(chain),
            u64(height),
            u64(nonce),
            u128(amount),
            hash_bytes,
            address_bytes,
            memo(memo_value),
            tags(tag_items),
        ]
    )


def main() -> int:
    chain = "auralite-test-1"
    zero_hash = bytes(32)
    zero_addr = bytes(20)

    vectors: list[tuple[str, str]] = [
        ("# AuraLite-Crypto C2 golden vectors", ""),
        ("# Generated by tools/gen_c2_vectors.py (independent implementation).", ""),
        ("# Format: key=<lowercase hex>. Do not edit by hand.", ""),
        ("# CODEC_VERSION=1, MAX_LENGTH=1048576, MAX_ITEMS=65536.", ""),
    ]

    record_1 = record(chain, "tx", False, 0, 0, 0, zero_hash, zero_addr, None, {})
    record_2 = record(
        chain,
        "vote",
        True,
        42,
        7,
        10**18,
        bytes(range(32)),
        bytes(range(20)),
        "hello",
        {"a": 1, "b": 2, "z": 9},
    )
    record_3 = record(
        chain,
        "block",
        False,
        2**64 - 1,
        2**64 - 1,
        2**128 - 1,
        bytes(255 - i for i in range(32)),
        bytes([0xAB] * 20),
        "aura-\u2713",  # multi-byte UTF-8, not Cyrillic/CJK
        {"alpha": 0, "omega": 2**64 - 1},
    )
    vectors += [
        ("record_1", record_1.hex()),
        ("record_2", record_2.hex()),
        ("record_3", record_3.hex()),
        ("codec_version", str(CODEC_VERSION)),
        ("max_length", str(MAX_LENGTH)),
    ]

    # Offsets inside record_1 (memo=None, tags={}).
    off_version = 0
    off_domain = 1
    off_flag = 2
    off_chain_len = 3
    chain_bytes = chain.encode("utf-8")
    off_height = off_chain_len + len(varint(len(chain_bytes))) + len(chain_bytes)
    off_memo = off_height + 8 + 8 + 16 + 32 + 20
    off_tags = off_memo + 1

    def patched(offset: int, value: int) -> bytes:
        out = bytearray(record_1)
        out[offset] = value
        return bytes(out)

    bad: list[tuple[str, bytes]] = [
        ("bad_version", patched(off_version, 2)),
        ("bad_domain_tag", patched(off_domain, 5)),
        ("bad_bool", patched(off_flag, 2)),
        ("bad_option_tag", patched(off_memo, 2)),
        ("trailing_byte", record_1 + b"\x00"),
        ("nonminimal_chain_len", record_1[:off_chain_len] + b"\x80\x00" + record_1[off_chain_len + 1 :]),
        ("length_too_large", record_1[:off_chain_len] + varint(MAX_LENGTH + 1) + record_1[off_chain_len + 1 :]),
        ("invalid_utf8_memo", record_1[:off_memo] + b"\x01\x01\xff" + record_1[off_tags:]),
        (
            "unordered_map",
            record_1[:off_memo] + b"\x00" + varint(2) + text("b") + u64(1) + text("a") + u64(2),
        ),
        (
            "duplicate_map_key",
            record_1[:off_memo] + b"\x00" + varint(2) + text("a") + u64(1) + text("a") + u64(2),
        ),
        ("nonminimal_map_count", record_1[:off_tags] + b"\x80\x00"),
        ("varint_overflow", record_1[:off_chain_len] + b"\xff" * 10 + b"\x7f"),
    ]
    vectors += [(key, value.hex()) for key, value in bad]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [key if not value else f"{key}={value}" for key, value in vectors]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(lines)} lines)")
    print(f"  record_1: {len(record_1)} bytes")
    print(f"  record_2: {len(record_2)} bytes")
    print(f"  record_3: {len(record_3)} bytes")
    print(f"  bad vectors: {len(bad)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
