#!/usr/bin/env python3
"""Generate the C1 golden vectors from an INDEPENDENT BIP-173 implementation.

This script deliberately does not import anything from the Rust crate. It is a
second, standalone bech32 encoder (the classic BIP-173 polymod/checksum, not
bech32m) used to pin down `Address::to_bech32()` in C1.

Usage:
    python3 tools/gen_c1_vectors.py
    make gen-c1-vectors

Output: crates/aura-types/tests/fixtures/c1_golden.txt
"""

from __future__ import annotations

from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "crates" / "aura-types" / "tests" / "fixtures" / "c1_golden.txt"

CHARSET = "qpzry9x8gf2tvdw0s3jn54khce6mua7l"
HRP = "aura"
GEN = [0x3B6A57B2, 0x26508E6D, 0x1EA119FA, 0x3D4233DD, 0x2A1462B3]


def polymod(values: list[int]) -> int:
    chk = 1
    for value in values:
        top = chk >> 25
        chk = (chk & 0x1FFFFFF) << 5 ^ value
        for i, gen in enumerate(GEN):
            if (top >> i) & 1:
                chk ^= gen
    return chk


def hrp_expand(hrp: str) -> list[int]:
    return [ord(c) >> 5 for c in hrp] + [0] + [ord(c) & 31 for c in hrp]


def create_checksum(hrp: str, data: list[int]) -> list[int]:
    values = hrp_expand(hrp) + data + [0] * 6
    mod = polymod(values) ^ 1
    return [(mod >> 5 * (5 - i)) & 31 for i in range(6)]


def convertbits(data: list[int], frombits: int, tobits: int, pad: bool = True) -> list[int]:
    acc = 0
    bits = 0
    ret: list[int] = []
    maxv = (1 << tobits) - 1
    for value in data:
        if value < 0 or (value >> frombits):
            raise ValueError("invalid data range")
        acc = (acc << frombits) | value
        bits += frombits
        while bits >= tobits:
            bits -= tobits
            ret.append((acc >> bits) & maxv)
    if pad:
        if bits:
            ret.append((acc << (tobits - bits)) & maxv)
    elif bits >= frombits or ((acc << (tobits - bits)) & maxv):
        raise ValueError("invalid padding")
    return ret


def bech32_encode(hrp: str, data: list[int]) -> str:
    combined = data + create_checksum(hrp, data)
    return hrp + "1" + "".join(CHARSET[d] for d in combined)


def address_bech32(pubkey_hash: bytes) -> str:
    if len(pubkey_hash) != 20:
        raise ValueError("pubkey hash must be 20 bytes")
    payload = [0x00] + list(pubkey_hash)  # version byte 0x00 || 20-byte hash
    return bech32_encode(HRP, convertbits(payload, 8, 5, pad=True))


def mutate_last_char(value: str) -> str:
    """Produce a definitely-invalid checksum by changing the final data char."""
    idx = len(value) - 1 - 6  # last data character, before the 6-char checksum
    old = value[idx]
    new = "q" if old != "q" else "p"
    return value[:idx] + new + value[idx + 1 :]


def main() -> int:
    vectors: list[tuple[str, str]] = []
    vectors.append(("# AuraLite-Crypto C1 golden vectors", ""))
    vectors.append(("# Generated by tools/gen_c1_vectors.py (independent BIP-173).", ""))
    vectors.append(("# Format: key=value. Do not edit by hand.", ""))
    vectors.append(("# bech32 variant: classic BIP-173 (polymod xor 1), NOT bech32m.", ""))
    vectors.append(("# address payload = version 0x00 || 20-byte pubkey hash.", ""))

    # Hash vectors: pure byte-level fixtures for the Hash newtype.
    vectors.append(("hash_zero", "00" * 32))
    vectors.append(("hash_asc", "".join(f"{i:02x}" for i in range(32))))
    vectors.append(("hash_desc", "".join(f"{255 - i:02x}" for i in range(32))))
    vectors.append(("hash_pattern", "deadbeeffeedface" * 4))

    addresses = {
        "address_1": bytes(range(20)),
        "address_2": bytes([0xAB] * 20),
        "address_3": bytes([0x00] * 20),
        "address_4": bytes.fromhex("deadbeeffeedface00112233445566778899aabb"),
    }
    encoded = {}
    for name, raw in addresses.items():
        encoded[name] = address_bech32(raw)
        vectors.append((f"{name}_bytes", raw.hex()))
        vectors.append((f"{name}_bech32", encoded[name]))

    vectors.append(("bad_checksum_1", mutate_last_char(encoded["address_1"])))
    vectors.append(("bad_checksum_2", mutate_last_char(encoded["address_2"])))
    vectors.append(("wrong_prefix", "cosmos" + encoded["address_1"][len(HRP) :]))
    vectors.append(("uppercase", encoded["address_1"].upper()))
    vectors.append(("amount_max", str(2**128 - 1)))
    vectors.append(("amount_units_per_coin", str(10**18)))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [f"{key}={value}" if value else key for key, value in vectors]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(lines)} lines)")
    for name, value in encoded.items():
        print(f"  {name}: {value}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
