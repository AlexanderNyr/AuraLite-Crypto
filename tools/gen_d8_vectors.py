#!/usr/bin/env python3
"""Generate 30 golden D8 CLI test vectors (crates/aura-node/tests/fixtures/d8_golden.txt)."""
from __future__ import annotations

import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "crates/aura-node/tests/fixtures/d8_golden.txt"
CHAIN_ID = "auralite-devnet-1"


def run_aura(args: list[str]) -> str:
    res = subprocess.run(
        ["cargo", "run", "--quiet", "-p", "aura-genesis", "--bin", "aura", "--", *args],
        cwd=REPO,
        text=True,
        capture_output=True,
        check=True,
    )
    return res.stdout.strip()


def parse_kv(text: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in text.splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            out[k.strip()] = v.strip()
    return out


def main() -> None:
    subprocess.run(
        ["cargo", "build", "--quiet", "-p", "aura-genesis", "--bin", "aura"],
        cwd=REPO,
        check=True,
    )
    aura_bin = REPO / "target/debug/aura"

    def call_bin(args: list[str]) -> str:
        res = subprocess.run(
            [str(aura_bin), *args],
            cwd=REPO,
            text=True,
            capture_output=True,
            check=True,
        )
        return res.stdout.strip()

    lines = [
        "# D8 CLI golden vectors (30 vectors across keys, tx, genesis, snapshot, upgrade).",
        "# Generated by tools/gen_d8_vectors.py; verified by crates/aura-node/tests/d8_cli.rs.",
        f"chain_id={CHAIN_ID}",
        "",
    ]

    vec_idx = 0

    # 1. 6 `keys` vectors (derive + sign + verify)
    for i in range(6):
        seed_hex = f"{i + 1:02x}" * 32
        msg_hex = f"cafebabe{i:04x}"
        kv = parse_kv(
            call_bin(
                [
                    "keys",
                    "sign",
                    "--seed",
                    seed_hex,
                    "--chain-id",
                    CHAIN_ID,
                    "--message",
                    msg_hex,
                ]
            )
        )
        lines.extend(
            [
                f"vector=d8_cli_{vec_idx:02d}",
                "kind=keys_sign",
                f"seed={seed_hex}",
                f"message={msg_hex}",
                f"public_key={kv['public_key']}",
                f"address={kv['address']}",
                f"signature={kv['signature']}",
                "",
            ]
        )
        vec_idx += 1

    # 2. 10 `tx transfer` / `tx decode` / `tx hash` vectors
    recipient_seed = "99" * 32
    recipient_addr = parse_kv(call_bin(["keys", "derive", "--seed", recipient_seed]))["address"]
    for i in range(10):
        seed_hex = f"{i + 16:02x}" * 32
        amount = (i + 1) * 12_500
        nonce = i
        gas_limit = 21_000 + i * 1_000
        tip = 1 + (i % 2)
        max_fee = 2 + tip + (i % 3)
        expiry = 100_000 + i * 100
        kv = parse_kv(
            call_bin(
                [
                    "tx",
                    "transfer",
                    "--seed",
                    seed_hex,
                    "--chain-id",
                    CHAIN_ID,
                    "--to",
                    recipient_addr,
                    "--amount",
                    str(amount),
                    "--nonce",
                    str(nonce),
                    "--gas-limit",
                    str(gas_limit),
                    "--max-fee",
                    str(max_fee),
                    "--tip",
                    str(tip),
                    "--expiry",
                    str(expiry),
                ]
            )
        )
        lines.extend(
            [
                f"vector=d8_cli_{vec_idx:02d}",
                "kind=tx_transfer",
                f"seed={seed_hex}",
                f"recipient={recipient_addr}",
                f"amount={amount}",
                f"nonce={nonce}",
                f"gas_limit={gas_limit}",
                f"max_fee={max_fee}",
                f"tip={tip}",
                f"expiry={expiry}",
                f"signer={kv['signer']}",
                f"txid={kv['txid']}",
                f"raw_tx={kv['raw_tx']}",
                "",
            ]
        )
        vec_idx += 1

    # 3. 2 `genesis` vectors against docs/spec/genesis-testnet.json
    genesis_file = "docs/spec/genesis-testnet.json"
    ghash = call_bin(["genesis", "hash", "--file", genesis_file])
    gshow = parse_kv(call_bin(["genesis", "show", "--file", genesis_file]))
    lines.extend(
        [
            f"vector=d8_cli_{vec_idx:02d}",
            "kind=genesis_hash",
            f"file={genesis_file}",
            f"genesis_hash={ghash}",
            "",
        ]
    )
    vec_idx += 1
    lines.extend(
        [
            f"vector=d8_cli_{vec_idx:02d}",
            "kind=genesis_show",
            f"file={genesis_file}",
            f"genesis_hash={gshow['genesis_hash']}",
            f"validator_set_hash={gshow['validator_set_hash']}",
            f"allocation_root={gshow['allocation_root']}",
            f"total_supply={gshow['total_supply']}",
            "",
        ]
    )
    vec_idx += 1

    # 4. 6 `snapshot` vectors (`create` + `verify`)
    for i in range(6):
        height = (i + 1) * 50
        state_root = f"{i + 0x40:02x}" * 32
        kv = parse_kv(
            call_bin(
                [
                    "snapshot",
                    "create",
                    "--chain-id",
                    CHAIN_ID,
                    "--height",
                    str(height),
                    "--state-root",
                    state_root,
                ]
            )
        )
        lines.extend(
            [
                f"vector=d8_cli_{vec_idx:02d}",
                "kind=snapshot",
                f"height={height}",
                f"state_root={state_root}",
                f"snapshot_hash={kv['snapshot_hash']}",
                "",
            ]
        )
        vec_idx += 1

    # 5. 6 `upgrade` vectors (`plan` + `verify`)
    for i in range(6):
        from_ver = i + 1
        to_ver = i + 2
        act_height = (i + 1) * 1_000
        bin_sha = f"{i + 0x70:02x}" * 32
        kv = parse_kv(
            call_bin(
                [
                    "upgrade",
                    "plan",
                    "--chain-id",
                    CHAIN_ID,
                    "--from-version",
                    str(from_ver),
                    "--to-version",
                    str(to_ver),
                    "--activation-height",
                    str(act_height),
                    "--binary-sha256",
                    bin_sha,
                ]
            )
        )
        lines.extend(
            [
                f"vector=d8_cli_{vec_idx:02d}",
                "kind=upgrade",
                f"from_version={from_ver}",
                f"to_version={to_ver}",
                f"activation_height={act_height}",
                f"binary_sha256={bin_sha}",
                f"plan_hash={kv['plan_hash']}",
                "",
            ]
        )
        vec_idx += 1

    assert vec_idx == 30, f"expected 30 vectors, generated {vec_idx}"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {vec_idx} D8 CLI golden vectors to {OUT.relative_to(REPO)}")


if __name__ == "__main__":
    main()
