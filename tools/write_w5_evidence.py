#!/usr/bin/env python3
"""Write W5 evidence (`docs/evidence/w5/`).

Reproducible bundle for the W5 gate ("10 human confirmed/denied scenarios;
NC: blind confirmation -> red"): captures the 10-scenario hardware suite,
`tools/nc_w5.py` (the mutation controls), and inventories the pinned fixture
against the independent generator. Model: tools/write_w4_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "w5"
FIXTURE = ROOT / "crates/aura-wallet/tests/fixtures/w5_hardware_vectors.json"
GENERATOR = ROOT / "tools/gen_w5_vectors.py"
RUNNER = ROOT / "crates/aura-wallet/tests/w5_hardware.rs"
HARDWARE = ROOT / "crates/aura-wallet/src/hardware.rs"
NAMED = "blind_confirmation_rejected"
TOTAL_NC = 656  # 650 through P6 + 6 W5 controls


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    test_log = run(["cargo", "test", "-p", "aura-wallet", "--features",
                    "insecure-test-kdf", "--test", "w5_hardware"])
    (EVIDENCE / "test-w5.log").write_text(test_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_w5.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    cases = doc["cases"]
    named_found = any(
        c["name"] == NAMED
        and c["expect_exit"] == 65
        and any("blind confirmation rejected" in line for line in c["expect_stderr"])
        for c in cases
    )
    inv = [
        "# W5 inventory (generated by tools/write_w5_evidence.py)",
        f"gate={doc['gate']}",
        f"vectors={len(cases)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"fixtures_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"runner_sha256={sha256(RUNNER)}",
        "cases:",
    ]
    inv += [f"  {c['name']} exit={c['expect_exit']}" for c in cases]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls cumulative")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    report = f"""# W5 closeout report — hardware keys with on-screen confirmation

Date: 2026-11-24. Gate (WALLET_PLAN row W5): "10 \"human confirmed/denied\"
scenarios; NC: blind confirmation -> red" — **satisfied**.

- **Confirmation binding**: `blind_confirmation_rejected` (the named control)
  — a `BlindSign` request is refused (`error: hardware: blind confirmation
  rejected`, exit 65) before any key use; mutation NC-1 (`tools/nc_w5.py`)
  makes the device sign blind requests and requires that test to go red.
- **Scenarios**: 10 deterministic cases from the independent oracle
  `tools/gen_w5_vectors.py` (display derivation, transfer/delegate payloads,
  Ed25519 RFC 8032-checked signatures under the fixed `tx` domain), asserted
  byte-for-byte by `tests/w5_hardware.rs` (11/11 with the count guard).
  Groups: confirm (3), deny (2), blind (1), display substitution (1), retry
  after denial (1), undecodable payload (1), foreign chain (1).
- **Mutation controls**: 6/6 PASS (blind acceptance, denial ignored, display
  binding dropped, chain check dropped, amount render altered, payload decode
  check dropped).
- **Device model** (docs/w5-hardware-plan.md): D-W5-1 the screen is derived
  exclusively from the transaction bytes, D-W5-2 only payloads that can be
  fully displayed are signed (`recipient||amount` for transfer, canonical
  stake payload for delegate/undelegate) and host previews are bound to the
  derived display, D-W5-3 nothing signs without `Armed -> Confirm` and a
  denial never latches, D-W5-4 signatures are ordinary AuraLite `tx` domain
  signatures (verifiable by the W3 offline path).

Receipts: `gates.txt`, `test-w5.log`, `nc.log`, `inventory.txt`, `SHA256SUMS`.
Regenerate with `make evidence-w5`. Public test data only — never use for funds.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    gates = [
        "# W5 gates",
        "hardware gate + 10 scenarios: PASS (11 tests: 10 scenarios + count guard)"
        if "test result: ok. 11 passed" in test_log
        else "hardware gate + 10 scenarios: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)" if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [FIXTURE, GENERATOR, RUNNER,
                  ROOT / "tools/nc_w5.py", HARDWARE,
                  EVIDENCE / "test-w5.log", EVIDENCE / "nc.log",
                  EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                  EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# W5 evidence — hardware keys with on-screen confirmation (10 scenarios)

Gate (WALLET_PLAN row W5): "10 \\"human confirmed/denied\\" scenarios; NC: blind
confirmation -> red". All fixtures are PUBLIC TEST DATA ONLY — never use for
funds.

- `test-w5.log` — `cargo test --features insecure-test-kdf --test w5_hardware`:
  {len(cases)} scenarios plus `vectors_file_has_exactly_10_unique_cases`,
  byte-for-byte against the independent oracle.
- `nc.log` — `tools/nc_w5.py` mutation controls (6): each source mutation must
  turn its named test red; compilation failure is not a valid red.
- `inventory.txt` — the 10 cases with exit codes, the named control, the
  cumulative NC total ({TOTAL_NC}) and SHA-256 pins of fixture, generator, runner.
- `report.md`, `gates.txt` — closeout report and gate summary.
- `SHA256SUMS` — digests of the deliverables and evidence files.

The vectors are produced by `tools/gen_w5_vectors.py` (pure Python: BLAKE3,
Ed25519 RFC 8032, domain_message, BIP-39/SLIP-0010, bech32). Regenerate with
`make gen-w5-vectors`; rebuild this bundle with `make evidence-w5`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} ({len(cases)} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
