#!/usr/bin/env python3
"""Record the C8 dependency delta against the FROZEN C3 baseline.

`docs/spec/c3-dependency-allowlist.txt` is pinned by the historical C3
evidence checksums and must never be rewritten. C8 therefore writes an
additive file `docs/spec/c8-dependency-addendum.txt` containing exactly the
external crates introduced after C3. `tools/check_deps.py` compares Cargo.lock
against the union of the baseline and all addenda.

Usage:
    python3 tools/record_c8_deps.py
    make record-c8-deps
"""

from __future__ import annotations

import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LOCK = REPO / "Cargo.lock"
BASELINE = REPO / "docs" / "spec" / "c3-dependency-allowlist.txt"
OUT = REPO / "docs" / "spec" / "c8-dependency-addendum.txt"

HEADER = [
    "# AuraLite-Crypto external dependency addendum (C8).",
    "# Generated by tools/record_c8_deps.py from Cargo.lock.",
    "# The C3 baseline file is FROZEN (pinned by docs/evidence/c3/SHA256SUMS);",
    "# this file lists ONLY crates added after C3. Any new phase adds its own",
    "# reviewed addendum. Checked by tools/check_deps.py inside `make test`.",
    "# C8 added serde_json for genesis CONFIG parsing only; consensus bytes",
    "# still come from aura-codec, and no crate uses a serde derive.",
]


def read_pairs(path: Path) -> list[tuple[str, str]]:
    result = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, version = line.split("=", 1)
        result.append((name, version))
    return result


def external_packages() -> list[tuple[str, str]]:
    data = tomllib.loads(LOCK.read_text(encoding="utf-8"))
    return sorted(
        (package["name"], package["version"])
        for package in data.get("package", [])
        if "source" in package
    )


def main() -> int:
    baseline = read_pairs(BASELINE)
    current = external_packages()
    removed = sorted(set(baseline) - set(current))
    if removed:
        print(f"ERROR: C3 baseline crates disappeared: {removed}")
        return 1
    added = sorted(set(current) - set(baseline))
    lines = HEADER + [f"{name}={version}" for name, version in added]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(added)} crates added since C3)")
    for name, version in added:
        print(f"  + {name}={version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
