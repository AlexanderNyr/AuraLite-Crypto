#!/usr/bin/env python3
"""Write W6 evidence (`docs/evidence/w6/`).

Reproducible bundle for the W6 gate ("signing shows the human the real tx
fields; NC: recipient substitution in UI -> red"): captures the 10-scenario
web wallet suite, `tools/nc_w6.py` (the mutation controls), the reproducible
`aura-keys` WASM build (`tools/build_aura_keys.py --check`), and inventories
the pinned fixtures against the independent generator. Model:
tools/write_w5_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "w6"
FIXTURE = ROOT / "crates/aura-wallet/tests/fixtures/w6_web_wallet_vectors.json"
WASM_FIXTURE = ROOT / "crates/aura-wallet/tests/fixtures/w6_aura_keys_wasm.txt"
WASM_ARTIFACT = ROOT / "clients/aura-keys/wasm/aura_keys.wasm"
GENERATOR = ROOT / "tools/gen_w6_vectors.py"
RUNNER = ROOT / "crates/aura-wallet/tests/w6_web.rs"
WEB = ROOT / "crates/aura-wallet/src/web.rs"
NAMED = "ui_recipient_substitution"
TOTAL_NC = 662  # 656 through W5 + 6 W6 controls


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    test_log = run(["cargo", "test", "-p", "aura-wallet", "--features",
                    "insecure-test-kdf", "--test", "w6_web"])
    (EVIDENCE / "test-w6.log").write_text(test_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_w6.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")
    wasm_log = run([sys.executable, "tools/build_aura_keys.py", "--check"])
    (EVIDENCE / "wasm-build.log").write_text(wasm_log, encoding="utf-8")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    cases = doc["cases"]
    named_found = any(
        c["name"] == NAMED
        and c["expect_exit"] == 65
        and any("recipient substitution" in line for line in c["expect_stderr"])
        and any("ui: to=" in line for line in c["expect_stdout"])
        for c in cases
    )
    inv = [
        "# W6 inventory (generated by tools/write_w6_evidence.py)",
        f"gate={doc['gate']}",
        f"vectors={len(cases)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"fixtures_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"runner_sha256={sha256(RUNNER)}",
        f"wasm_fixture_sha256={sha256(WASM_FIXTURE)}",
        f"wasm_artifact_sha256={sha256(WASM_ARTIFACT)}",
        "cases:",
    ]
    inv += [f"  {c['name']} exit={c['expect_exit']}" for c in cases]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls cumulative")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    report = f"""# W6 closeout report — web wallet with real-tx-field confirmation

Date: 2026-11-25. Gate (WALLET_PLAN row W6): "signing shows the human the
**real** tx fields; NC: recipient substitution in UI -> red" — **satisfied**.

- **Real fields**: `ui_recipient_substitution` (the named control) — a deep
  link claiming a recipient that disagrees with the bytes is refused
  (`error: web: recipient substitution`, exit 65) after the dialog has shown
  the **real** `ui: to=…` line derived from the transaction; mutation NC-1
  (`tools/nc_w6.py`) drops the claim comparison and NC-6 renders the line
  from the wrong source — both must turn that test red.
- **Scenarios**: 10 deterministic cases from the independent oracle
  `tools/gen_w6_vectors.py` (W3 envelopes, `recipient||amount` payloads,
  Ed25519 RFC 8032-checked signatures under the fixed `tx` domain), asserted
  byte-for-byte by `tests/w6_web.rs` (11/11 with the count guard). Groups:
  confirm with real fields (2), claim substitutions (2), deep-link schema
  (2), phishing origins (2), blind signing (1), unsupported kind (1).
- **Mutation controls**: 6/6 PASS (recipient comparison dropped, amount
  comparison dropped, homoglyph check dropped, deep-link whitelist dropped,
  blind signing accepted, recipient line rendered from the wrong source).
- **WASM build**: `clients/aura-keys` (own workspace and lockfile) compiles
  `crates/aura-wallet/src/web.rs` verbatim and exposes it through a
  deterministic C ABI with **zero imports**; `tools/build_aura_keys.py` builds
  it twice into independent target directories and refuses to pin unless the
  two artifacts are byte-identical — size/sha256/exports are pinned in
  `tests/fixtures/w6_aura_keys_wasm.txt` and the shipped
  `clients/aura-keys/wasm/aura_keys.wasm`.
- **Device model** (docs/w6-web-wallet-plan.md): D-W6-1 confirmation fields
  come only from the signed bytes, D-W6-2 signing requires the rendered view
  (`aura_keys_sign` re-derives and refuses a doctored `shown` view;
  `aura_keys_sign_without_view` is an always-refusing tripwire), D-W6-3 the
  phishing policy (https-only, no userinfo, ASCII host, official allowlist,
  homoglyphs -> `suspicious origin`), D-W6-4 the strict
  `auralite://sign?tx=…` schema, D-W6-5 honest scope (transfer only; the
  extension under `clients/wallet-web/` is untrusted glue).

Receipts: `gates.txt`, `test-w6.log`, `nc.log`, `wasm-build.log`,
`inventory.txt`, `SHA256SUMS`. Regenerate with `make evidence-w6`. Public
test data only — never use for funds.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    gates = [
        "# W6 gates",
        "real-fields gate + 10 scenarios: PASS (11 tests: 10 scenarios + count guard)"
        if "test result: ok. 11 passed" in test_log
        else "real-fields gate + 10 scenarios: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)" if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
        "wasm artifact reproducible: PASS (two builds byte-identical, pinned)"
        if "PINNED HASHES MATCH" in wasm_log and "exit=0" in wasm_log
        else "wasm artifact reproducible: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [FIXTURE, WASM_FIXTURE, WASM_ARTIFACT, GENERATOR, RUNNER,
                  ROOT / "tools/nc_w6.py", WEB,
                  ROOT / "clients/aura-keys/src/lib.rs",
                  EVIDENCE / "test-w6.log", EVIDENCE / "nc.log",
                  EVIDENCE / "wasm-build.log",
                  EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                  EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# W6 evidence — web wallet with real-tx-field confirmation (10 scenarios)

Gate (WALLET_PLAN row W6): "signing shows the human the **real** tx fields;
NC: recipient substitution in UI -> red". All fixtures are PUBLIC TEST DATA
ONLY — never use for funds.

- `test-w6.log` — `cargo test --features insecure-test-kdf --test w6_web`:
  {len(cases)} scenarios plus `vectors_file_has_exactly_10_unique_cases`,
  byte-for-byte against the independent oracle.
- `nc.log` — `tools/nc_w6.py` mutation controls (6): each source mutation must
  turn its named test red; compilation failure is not a valid red.
- `wasm-build.log` — `tools/build_aura_keys.py --check`: the `aura-keys` WASM
  artifact rebuilt twice into independent target directories, byte-identical,
  matching the pinned hash in `tests/fixtures/w6_aura_keys_wasm.txt`.
- `inventory.txt` — the 10 cases with exit codes, the named control, the WASM
  pins, the cumulative NC total ({TOTAL_NC}) and SHA-256 pins of fixture,
  generator, runner.
- `report.md`, `gates.txt` — closeout report and gate summary.
- `SHA256SUMS` — digests of the deliverables and evidence files.

The vectors are produced by `tools/gen_w6_vectors.py` (pure Python: BLAKE3,
Ed25519 RFC 8032, domain_message, BIP-39/SLIP-0010, bech32). Regenerate with
`make gen-w6-vectors`; rebuild this bundle with `make evidence-w6`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} ({len(cases)} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
