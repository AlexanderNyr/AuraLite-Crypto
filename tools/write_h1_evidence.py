#!/usr/bin/env python3
"""Write H1 evidence (`docs/evidence/h1/`).

Reproducible bundle for the H1 gate ("CI fails on a known vulnerable
version; remove deny -> red"): captures `tools/check_supply_chain.py`
(self-test + repository check), `tools/nc_h1.py` (mutation controls), the
auxiliary tool versions, and a signed-artifacts manifest (Ed25519 demo key
over repository artifacts). Model: tools/write_h0_evidence.py.
"""
from __future__ import annotations

import base64
import hashlib
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools import sign_release as sign_mod  # noqa: E402

EVIDENCE = ROOT / "docs" / "evidence" / "h1"
FIX = ROOT / "tools" / "fixtures"
NAMED = "remove_deny"
TOTAL_NC = 436  # 430 through H0 + 6 H1 controls
ARTIFACTS = [
    "Cargo.lock", "sbom.cdx.json", "deny.toml", "rust-toolchain.toml",
    "patches/0058-W0-wallet-baseline.patch",
    "patches/0059-W1-crypto-keystore.patch",
    "patches/0060-W2-wallet-cli.patch",
    "patches/0061-W3-offline-signing.patch",
    "patches/0062-W4-Multisig-phase-closed-3-of-5-gate-22-vectors-6-mu.patch",
    "patches/0063-H0-Threat-model-phase-closed-32-owned-scenarios-6-mu.patch",
]


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    check_log = (run([sys.executable, "tools/check_supply_chain.py", "--selftest"])
                 + run([sys.executable, "tools/check_supply_chain.py"]))
    (EVIDENCE / "check.log").write_text(check_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_h1.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")

    (EVIDENCE / "tool-versions.txt").write_text(
        "# Auxiliary (non-gate) tool versions pinned by the phase\n"
        "cargo-deny 0.20.2 (x86_64-unknown-linux-musl, EmbarkStudios release)\n"
        "gitleaks 8.30.1 (linux x64, gitleaks release)\n"
        "rustc 1.99.1 (rust-toolchain.toml channel)\n",
        encoding="utf-8")

    manifest = ["# Ed25519 demo-key signatures over repository artifacts (D-H1-5)",
                f"# pubkey {sign_mod.public_key().hex()}",
                "# <path> <sha256> <sig-b64 over AuraLite-Crypto/release-digest-v1\\0 || sha256>"]
    for rel in ARTIFACTS:
        path = ROOT / rel
        if not path.exists():
            continue
        digest = hashlib.sha256(path.read_bytes()).digest()
        sig = sign_mod.sign_message(sign_mod.PREFIX + digest)
        manifest.append(f"{rel} {digest.hex()} {base64.b64encode(sig).decode()}")
    (EVIDENCE / "signed-artifacts.txt").write_text("\n".join(manifest) + "\n",
                                                  encoding="utf-8")

    vectors = (FIX / "h1_supply_chain_vectors.json").read_text(encoding="utf-8")
    import json
    vec = json.loads(vectors)
    named_found = any(v["case"] == "vulnerable_lock_denied" and v["expect"] == "deny"
                      for v in vec["verdicts"])
    inv = [
        "# H1 inventory (generated by tools/write_h1_evidence.py)",
        f"gate={vec['format']}",
        f"verdicts={len(vec['verdicts'])}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"lock_packages={vec['lock']['packages']}",
        f"lock_sha256={vec['lock']['sha256']}",
        f"sbom_sha256={vec['sbom']['sha256']}",
        f"advisories_sha256={vec['advisories_sha256']}",
        f"release_pubkey={vec['release_pubkey_hex']}",
        f"signed_artifacts={len(ARTIFACTS)}",
        "verdicts:",
    ]
    inv += [f"  {v['case']} expect={v['expect']}" for v in vec["verdicts"]]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    report = f"""# H1 closeout report — supply chain

Date: 2026-11-14. Gate (SECURITY_PLAN row H1): "CI fails on a known
vulnerable version; NC: remove deny -> red" — **satisfied**.

- **Vulnerable-version gate**: `tools/check_supply_chain.py` refuses the
  negative fixture `tools/fixtures/h1_vulnerable.lock` with
  `error: supply-chain: denied RUSTSEC-TEST-0001 (demo-vulnerable v0.9.0)`
  (exit 1) — the deterministic, offline "CI fails" demonstration. The deny
  verdicts come from the pinned advisory snapshot
  (`tools/fixtures/h1_advisories.json`, D-H1-2).
- **Named control** ({NAMED}): `tools/nc_h1.py` NC-1 weakens the advisory
  deny and requires the self-test case `vulnerable_lock_denied` to go red.
- **Pinning**: `rust-toolchain.toml` (1.99.1), committed `Cargo.lock` with a
  pinned digest and zero unpinned git sources.
- **SBOM**: deterministic CycloneDX 1.5 (`sbom.cdx.json`, D-H1-3) with a
  pinned digest; drift fails the gate.
- **Secrets**: gitleaks-class scanner (`tools/scan_secrets.py`, D-H1-4) with
  a planted-secret fixture proving detection and a clean-repo verdict.
- **Signatures**: Ed25519 demo-key detached signatures (D-H1-5) over
  repository artifacts (`signed-artifacts.txt`, pubkey pinned in
  `docs/release-pubkey.txt`); forged signatures are refused.
- **Vectors**: {len(vec['verdicts'])} self-test verdicts from the oracle
  `tools/gen_h1_vectors.py` (11/11 PASS); **mutation controls 6/6 PASS**
  (deny, toolchain pin, lockfile digest, sbom, secret rule, signature).
- **Auxiliary tools** (non-gate, versions pinned in `tool-versions.txt`):
  cargo-deny 0.20.2, gitleaks 8.30.1 (D-H1-6).

Receipts: `gates.txt`, `check.log`, `nc.log`, `tool-versions.txt`,
`signed-artifacts.txt`, `inventory.txt`, `SHA256SUMS`. Regenerate with
`make evidence-h1`. Public project material only.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    gates = [
        "# H1 gates",
        f"supply chain vectors: PASS ({len(vec['verdicts'])}/"
        f"{len(vec['verdicts'])} self-test verdicts)"
        if f"RESULT: {len(vec['verdicts'])}/{len(vec['verdicts'])} supply-chain vectors PASS"
        in check_log else "supply chain vectors: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)" if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")

    sources = [FIX / "h1_supply_chain_vectors.json", FIX / "h1_advisories.json",
               FIX / "h1_vulnerable.lock", FIX / "h1_secret_leak.txt",
               FIX / "h1_release_demo.bin", FIX / "h1_release_demo.bin.sig",
               ROOT / "tools" / "check_supply_chain.py",
               ROOT / "tools" / "scan_secrets.py",
               ROOT / "tools" / "sign_release.py",
               ROOT / "tools" / "gen_h1_sbom.py",
               ROOT / "tools" / "gen_h1_vectors.py",
               ROOT / "tools" / "nc_h1.py",
               ROOT / "sbom.cdx.json", ROOT / "deny.toml",
               ROOT / "docs" / "release-pubkey.txt"]
    sums = [f"{sha256(p)}  {p.relative_to(ROOT)}" for p in sources if p.exists()]
    sums += [f"{sha256(p)}  {p.relative_to(ROOT)}"
             for p in [EVIDENCE / "check.log", EVIDENCE / "nc.log",
                       EVIDENCE / "tool-versions.txt", EVIDENCE / "signed-artifacts.txt",
                       EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                       EVIDENCE / "report.md"]]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# H1 evidence — supply-chain gate ({len(vec['verdicts'])} verdicts)

Gate (SECURITY_PLAN row H1): "CI fails on a known vulnerable version; NC:
remove deny -> red".

- `check.log` — `tools/check_supply_chain.py`: the self-test (vulnerable
  lockfile -> denied, planted secret -> detected, forged signature ->
  refused) and the repository check (pins, deny, sbom, secrets, signatures).
- `nc.log` — `tools/nc_h1.py` mutation controls (6), named = remove deny.
- `signed-artifacts.txt` — Ed25519 demo-key signatures over repository
  artifacts (D-H1-5); verify with `tools/sign_release.py verify`.
- `tool-versions.txt` — auxiliary tool pins (cargo-deny 0.20.2, gitleaks
  8.30.1); the gate itself never shells out to them (D-H1-6).
- `inventory.txt` — verdicts, digests and the cumulative NC total ({TOTAL_NC}).
- `report.md`, `gates.txt`, `SHA256SUMS`.

Regenerate: `make gen-h1-vectors`, `make gen-h1-sbom`, `make evidence-h1`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} ({len(vec['verdicts'])} verdicts)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
