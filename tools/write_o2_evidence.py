#!/usr/bin/env python3
"""Write O2 evidence (`docs/evidence/o2/`).

Reproducible bundle for the O2 gate ("ROADMAP §5 M0 and M1 criteria met"):
captures the 10-scenario milestone suite, `tools/nc_o2.py` (the mutation
controls), the measured M0/M1 receipts (`aurad-receipt`), the receipt check
(`aura-milestone check`), and the multi-process M1 acceptance
(`tests/d7_devnet.rs`). Model: tools/write_o1_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "o2"
FIXTURE = ROOT / "crates/aura-testkit/tests/fixtures/o2_milestone_vectors.json"
GENERATOR = ROOT / "tools/gen_o2_vectors.py"
RUNNER = ROOT / "crates/aura-testkit/tests/o2_milestones.rs"
MILESTONE_MODULE = ROOT / "crates/aura-testkit" / "src" / "milestone.rs"
RECEIPT_BIN = ROOT / "crates/aura-node" / "src" / "bin" / "aurad-receipt.rs"
HOW_TO_RUN = ROOT / "docs" / "how-to-run.md"
NAMED = "m0_root_drift_refused"
TOTAL_NC = 686  # 680 through O1 + 6 O2 controls


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    test_log = run(["cargo", "test", "-p", "aura-testkit", "--test", "o2_milestones"])
    (EVIDENCE / "test.log").write_text(test_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_o2.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")
    receipts_log = run(["make", "milestone-receipts"])
    (EVIDENCE / "receipts.log").write_text(receipts_log, encoding="utf-8")
    check_log = run(["make", "milestone-check"])
    (EVIDENCE / "milestone-check.log").write_text(check_log, encoding="utf-8")
    acceptance_log = run(["cargo", "test", "-p", "aura-node", "--test", "d7_devnet"])
    (EVIDENCE / "m1-acceptance.log").write_text(acceptance_log, encoding="utf-8")

    measured = ROOT / "release" / "milestone.txt"
    if measured.is_file():
        shutil.copyfile(measured, EVIDENCE / "milestone.txt")
    else:
        (EVIDENCE / "milestone.txt").write_text("missing\n", encoding="utf-8")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    cases = doc["cases"]
    named_found = any(
        c["name"] == NAMED
        and c.get("nc_ref") == 1
        and c["exit"] == 65
        and "m0 state root drift" in c["stderr"]
        for c in cases
    )
    inv = [
        "# O2 inventory (generated by tools/write_o2_evidence.py)",
        f"gate={doc['gate']}",
        f"vectors={len(cases)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"fixtures_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"runner_sha256={sha256(RUNNER)}",
        f"milestone_module_sha256={sha256(MILESTONE_MODULE)}",
        f"receipt_bin_sha256={sha256(RECEIPT_BIN)}",
        f"how_to_run_sha256={sha256(HOW_TO_RUN)}",
        f"milestone_txt_sha256={sha256(EVIDENCE / 'milestone.txt')}",
        "cases:",
    ]
    inv += [f"  {c['name']} exit={c['exit']} nc={c.get('nc_ref', '-')}" for c in cases]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls cumulative")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    measured_text = (EVIDENCE / "milestone.txt").read_text(encoding="utf-8")
    report = f"""# O2 closeout report — M0/M1 gates (the milestone receipts)

Date: 2026-11-25. Gate (OPS_PLAN row O2): "ROADMAP §5 M0 and M1 criteria
met" — **satisfied on measured receipts** (`milestone.txt`, recorded above;
`aurad-receipt` produced these values on the shipped pipeline and cluster —
nothing in this bundle is fabricated).

- M0 (genesis lib): `make test` green; genesis -> 1000 tx -> byte-identical
  state root on 2 runs (`m0 state_root` lines identical).
- M1 (devnet): 4 validators, block interval <= 1 s, >= 100 committed
  blocks without desync, RPC returns a positive balance (the balance read
  goes through the shipped `aura_rpc::RpcService` dispatch; the socket path
  is the multi-process acceptance below).

- **The gate**: `{NAMED}` (the named control) feeds the checker a receipt
  whose two `m0 state_root` lines differ and expects `error: milestone:
  m0 state root drift` (exit 65); mutation NC-1 (`tools/nc_o2.py`) drops
  the root-equality check and the case must turn red.
- **Scenarios**: 10 deterministic cases from the independent oracle
  `tools/gen_o2_vectors.py`, asserted byte-for-byte by `tests/o2_milestones.rs`
  (11/11 with the count guard) against `aura_testkit::milestone`.
- **Mutation controls**: 6/6 PASS (root-equality check [named],
  validator-count check, desync check, height check, rpc-balance check,
  unknown-line strictness).
- **M1 acceptance (multi-process)**: `tests/d7_devnet.rs` — four real
  `aurad` processes, 100 finalized blocks with identical head/state_root,
  JSON-RPC balance after a faucet transfer, survival of a 1-of-4 outage
  (`m1-acceptance.log`).
- **Device model** (docs/o2-m0-m1-plan.md): D-O2-1 the checked receipt
  format (`rule milestones-v1`, strict, no commands); D-O2-2 M0 measured on
  the real D2/D3 pipeline (two fresh replays); D-O2-3 M1 measured on the
  real 4-validator `DevnetCluster` + the real RPC dispatch; D-O2-4 the
  "how to run" doc (`docs/how-to-run.md`) and these first receipts;
  D-O2-5 two independent implementations (Python oracle vs the shipped
  checker).

Measured receipt (milestone.txt):

```
{measured_text}```

Receipts: `gates.txt`, `test.log`, `nc.log`, `receipts.log`,
`milestone-check.log`, `m1-acceptance.log`, `milestone.txt`,
`inventory.txt`, `SHA256SUMS`. Regenerate with `make evidence-o2`.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    gates = [
        "# O2 gates",
        "milestone gate + 10 scenarios: PASS (11 tests: 10 scenarios + count guard)"
        if "test result: ok. 11 passed" in test_log
        else "milestone gate + 10 scenarios: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)"
        if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
        "M0/M1 measured receipts: PASS (milestones=ok m0=ok m1=ok)"
        if "milestones=ok m0=ok m1=ok" in check_log and "exit=0" in check_log
        else "M0/M1 measured receipts: FAIL",
        "M1 multi-process acceptance (d7): PASS"
        if "test result: ok" in acceptance_log and "exit=0" in acceptance_log
        else "M1 multi-process acceptance (d7): FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")
    failed = [gate for gate in gates if gate.endswith("FAIL")]
    if failed:
        print("O2 EVIDENCE: FAIL — " + "; ".join(failed))
        return 1

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [FIXTURE, GENERATOR, RUNNER, MILESTONE_MODULE, RECEIPT_BIN,
                  HOW_TO_RUN, ROOT / "tools/nc_o2.py",
                  EVIDENCE / "test.log", EVIDENCE / "nc.log",
                  EVIDENCE / "receipts.log", EVIDENCE / "milestone-check.log",
                  EVIDENCE / "m1-acceptance.log", EVIDENCE / "milestone.txt",
                  EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                  EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# O2 evidence — M0/M1 gates (10 scenarios)

Gate (OPS_PLAN row O2): "ROADMAP §5 M0 and M1 criteria met". Named control:
{NAMED}. The receipts in `milestone.txt` are measured by `aurad-receipt` on
the shipped pipeline/cluster; `aura-milestone check` validates them against
the criteria. `docs/how-to-run.md` is the operator quickstart.

- `test.log`: `cargo test -p aura-testkit --test o2_milestones` (11 tests).
- `nc.log`: `tools/nc_o2.py` mutation controls (6/6).
- `receipts.log`: the measured M0/M1 run (`aurad-receipt`).
- `milestone-check.log`: `aura-milestone check` over the measured receipts.
- `m1-acceptance.log`: the multi-process `d7_devnet` acceptance (four real
  `aurad` processes).
- `milestone.txt`: the first M0/M1 receipts (committed with the phase).
- `inventory.txt`: case -> NC mapping and sha256 of fixture/generator/
  runner/module/receipt bin; ends with `TOTAL: {TOTAL_NC}`.
- `gates.txt` / `report.md` / `SHA256SUMS`: the receipts.

Regenerate with `make evidence-o2`; every sha256 in `SHA256SUMS` can be
recomputed with `sha256sum -c`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} (10 vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
