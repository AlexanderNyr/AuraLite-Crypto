#!/usr/bin/env python3
"""Record the X0 dependency delta (none — state sync uses existing crates).

The C3 baseline is frozen historical evidence. X0 adds NO external crate: the
determinism census is a hand-written WASM binary classifier inside
`aura-exec`, which until now was an honest empty placeholder. `wasmtime` is
deliberately NOT a dependency yet — X0's DoD is a census plus a restrictive
configuration and makes no runtime claim. The engine is pinned in X1 together
with fuel metering, memory ceilings and the zero-import sandbox, because fuel
semantics are version sensitive and a version bump must be a protocol
decision, not a silent `cargo update`.

Usage:
    python3 tools/record_x0_deps.py
    make record-x0-deps
"""
from __future__ import annotations

import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "evidence" / "x0-dependency-addendum.txt"


def read_pairs(path: Path) -> set[tuple[str, str]]:
    out = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            name, version = line.split("=", 1)
            out.add((name, version))
    return out


def main() -> int:
    data = tomllib.loads((REPO / "Cargo.lock").read_text(encoding="utf-8"))
    current = {
        (p["name"], p["version"])
        for p in data.get("package", [])
        if "source" in p
    }
    known = read_pairs(REPO / "docs" / "spec" / "c3-dependency-allowlist.txt")
    for path in (REPO / "docs" / "spec").glob("*-dependency-addendum.txt"):
        known |= read_pairs(path)
    for path in (REPO / "docs" / "evidence").glob("*-dependency-addendum.txt"):
        if path != OUT:
            known |= read_pairs(path)
    missing = sorted(current - known)
    if missing:
        print(f"ERROR: unrecorded crates: {missing}")
        return 1
    OUT.write_text(
        "\n".join([
            "# AuraLite-Crypto external dependency addendum (X0).",
            "# Generated by tools/record_x0_deps.py from Cargo.lock.",
            "# X0 determinism census parses WASM by hand: no engine, no new crate.",
            "# No new external crate, no new workspace crate in this phase.",
            "# Deferred on purpose: wasmtime is pinned in X1, not here.",
        ]) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(REPO)} (0 new crates)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
