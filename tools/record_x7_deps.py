#!/usr/bin/env python3
"""Record the X7 dependency delta: none.

X7 is a gate, not a subsystem: a deterministic scenario generator and a replay
driver inside `aura-exec` (`detcheck`), one binary (`x7-run`) and a test. It adds
**no dependency at all** — not external, not a workspace edge — and it does not
add a contract: the scenario executes the artifacts X4 and X6 already shipped, and
pins their BLAKE3 in the fixture.

This addendum exists to make that statement checkable: it records the counts
before and after, and the size of the default `aura-exec` build graph, which is
what a node actually compiles.

Usage:
    python3 tools/record_x7_deps.py
    make record-x7-deps
"""

from __future__ import annotations

import subprocess
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "evidence" / "x7-dependency-addendum.txt"

WORKSPACE_DEPS: list[str] = []  # a gate adds no edge: it uses what aura-exec already has


def sh(command: str) -> str:
    result = subprocess.run(
        command, shell=True, cwd=REPO, capture_output=True, text=True, check=False
    )
    return (result.stdout + result.stderr).strip()


def main() -> int:
    external = sh("grep -c '^source = ' Cargo.lock")
    default_graph = sh("cargo tree -p aura-exec --edges normal -q | sort -u | wc -l")
    workspace_graph = sh("cargo tree -p aura-exec --edges normal -q | wc -l")
    deps = "\n".join(f"#   aura-exec -> {name}" for name in WORKSPACE_DEPS) or "#   (none)"
    text = f"""# AuraLite-Crypto external dependency addendum (X7).
# Generated by tools/record_x7_deps.py from Cargo.lock.
#
# X7 adds NO new external crate and NO new workspace crate. The scenario generator,
# the replay driver and the rolling digest are Rust inside `aura-exec`; the only new
# binary links the crates the workspace already built. The lock does not move.
# This file therefore contains no `name=version` lines: it is a statement that
# the allowlist is unchanged, and the dependency gate still validates it against
# Cargo.lock.
#
# No timestamp: this file is checksummed in docs/evidence/x7/SHA256SUMS, so
# regenerating it must reproduce it byte for byte.
# External crates in Cargo.lock: {external} (unchanged since X1)
# New external crates in X7: 0
# New workspace crates in X7: 0
#
# New WORKSPACE dependencies of aura-exec:
{deps}
#
# Why: the SDK is a leaf. `aura-sdk` depends on nothing but `aura-sdk-macros`
# (proc macros only), and `aura-sdk-macros` depends on syn/quote/proc-macro2.
# The SDK is therefore usable BOTH from a `no_std` contract for
# wasm32-unknown-unknown and from host tests; it never links the node, and
# nothing in the node depends on it except a dev-dependency in the SDK's own
# tests, which is the direction that keeps a contract's dependency graph clean.
#
# Build graph for `cargo tree -p aura-exec --edges normal`:
#   unique lines: {default_graph}   (X1 baseline: 10, X2: 93, X7: 93)
#   total lines:  {workspace_graph}
# The growth is the C1/C3/C6/C7 stack that aura-exec now links against instead
# of only mentioning it in comments. It is compiled into every node already.
#
# Engine pins unchanged: wasmi =2.0.0 (default), wasmtime =50.0.0 (feature
# wasmtime-engine). X7 needed no engine change in wasmi's *version*: the hosted
# policy already required mutable globals, bulk memory and indirect calls to be
# enabled in `Config`, which is a configuration change inside the pinned version
# (see docs/evidence/x7/report.md). The wasmtime backend still refuses hosted
# execution with SandboxError::EngineUnavailable.
"""
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
