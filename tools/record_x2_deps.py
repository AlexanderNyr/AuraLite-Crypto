#!/usr/bin/env python3
"""Record the X2 dependency delta: none.

X2 needs the state layer to execute contracts, so `aura-exec` gains three
**workspace** dependencies — `aura-types`, `aura-crypto`, `aura-state`. All three
already existed in the lock, so the external dependency count does not move and
no new supply-chain surface is added.

This addendum exists to make that statement checkable: it records the counts
before and after, and the size of the default `aura-exec` build graph, which is
what a node actually compiles.

Usage:
    python3 tools/record_x2_deps.py
    make record-x2-deps
"""

from __future__ import annotations

import subprocess
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "evidence" / "x2-dependency-addendum.txt"

WORKSPACE_DEPS = ["aura-types", "aura-crypto", "aura-state"]


def sh(command: str) -> str:
    result = subprocess.run(
        command, shell=True, cwd=REPO, capture_output=True, text=True, check=False
    )
    return (result.stdout + result.stderr).strip()


def main() -> int:
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    external = sh("grep -c '^source = ' Cargo.lock")
    default_graph = sh("cargo tree -p aura-exec --edges normal -q | sort -u | wc -l")
    workspace_graph = sh("cargo tree -p aura-exec --edges normal -q | wc -l")
    deps = "\n".join(f"#   aura-exec -> {name}" for name in WORKSPACE_DEPS)
    text = f"""# AuraLite-Crypto external dependency addendum (X2).
# Generated by tools/record_x2_deps.py from Cargo.lock.
#
# X2 adds NO external crate. This file therefore contains no `name=version`
# lines: it is a statement that the allowlist is unchanged, and the dependency
# gate still validates it against Cargo.lock.
#
# Generated (UTC): {stamp}
# External crates in Cargo.lock: {external} (unchanged since X1)
# New external crates in X2: 0
#
# New WORKSPACE dependencies of aura-exec (all already in the lock):
{deps}
#
# Why: the ABI writes into the S3 overlay (StateView), encodes canonical account
# values (C7 Account) and moves Amount/Address (C1). Those crates were already
# in the workspace and in every node build, so X2 adds code inside the crate
# boundary rather than supply chain outside it.
#
# Build graph for `cargo tree -p aura-exec --edges normal`:
#   unique lines: {default_graph}   (X1 baseline: 10)
#   total lines:  {workspace_graph}
# The growth is the C1/C3/C6/C7 stack that aura-exec now links against instead
# of only mentioning it in comments. It is compiled into every node already.
#
# Engine pins unchanged: wasmi =2.0.0 (default), wasmtime =50.0.0 (feature
# wasmtime-engine). The X2 host ABI is implemented on the wasmi backend; the
# wasmtime backend returns SandboxError::EngineUnavailable for hosted execution
# rather than pretending to run it (see docs/evidence/x2/report.md).
"""
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
