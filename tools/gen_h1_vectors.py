#!/usr/bin/env python3
"""Deterministic H1 oracle: supply-chain fixtures and verdict vectors.

Generates:
  tools/fixtures/h1_advisories.json      — pinned advisory snapshot (TEST ids)
  tools/fixtures/h1_vulnerable.lock      — lockfile resolving a denied crate
  tools/fixtures/h1_secret_leak.txt      — planted secrets (scanner must catch)
  tools/fixtures/h1_release_demo.bin     — demo release artifact
  tools/fixtures/h1_release_demo.bin.sig — detached Ed25519 signature (demo key)
  tools/fixtures/h1_supply_chain_vectors.json — digests + expected verdicts

Independent of `tools/check_supply_chain.py` (the gate re-derives and
compares). Regenerate with `make gen-h1-vectors`. Design:
docs/h1-supply-chain-plan.md (D-H1-1..6).
"""
from __future__ import annotations

import base64
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools import gen_h1_sbom as sbom_mod  # noqa: E402
from tools import sign_release as sign_mod  # noqa: E402

FIX = ROOT / "tools" / "fixtures"
LOCK = ROOT / "Cargo.lock"
TOOLCHAIN = ROOT / "rust-toolchain.toml"
SBOM = ROOT / "sbom.cdx.json"

ADVISORIES = {
    "format": "AURALITE-ADVISORY-SNAPSHOT-V1",
    "note": ("Pinned offline snapshot for the deterministic deny gate. "
             "RUSTSEC-TEST-* ids are local test identifiers, never real "
             "RUSTSEC advisories (D-H1-2)."),
    "advisories": [
        {"id": "RUSTSEC-TEST-0001", "crate": "demo-vulnerable",
         "patched": ">=1.0.0", "title": "test-only advisory: demo-vulnerable"},
        {"id": "RUSTSEC-TEST-0002", "crate": "demo-vulnerable-two",
         "patched": ">=0.4.2", "title": "test-only advisory: demo-vulnerable-two"},
    ],
}

VULNERABLE_LOCK = """# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "demo-safe"
version = "1.2.3"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "1111111111111111111111111111111111111111111111111111111111111111"

[[package]]
name = "demo-vulnerable"
version = "0.9.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "2222222222222222222222222222222222222222222222222222222222222222"
"""

SECRET_LEAK = """# intentional H1 scanner fixture — planted secrets (allow-listed file;
# kept PEM-free so the W0 tree-search gate stays clean — the private-key
# rule is proven by the in-memory pem_block_detected vector instead)
[database]
password = "hunter2-demo-planted-secret"
token = "ghp_demo00000000000000000000000000"
aws_access_key_id = "AKIADEMO00000000DEMO"
authorization = "Bearer demotokendemotokendemotoken00"
"""

DEMO_ARTIFACT = b"AuraLite-Crypto/h1-release-demo-artifact-v1\n"


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    FIX.mkdir(parents=True, exist_ok=True)

    (FIX / "h1_advisories.json").write_text(
        json.dumps(ADVISORIES, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    (FIX / "h1_vulnerable.lock").write_text(VULNERABLE_LOCK, encoding="utf-8")
    (FIX / "h1_secret_leak.txt").write_text(SECRET_LEAK, encoding="utf-8")
    (FIX / "h1_release_demo.bin").write_bytes(DEMO_ARTIFACT)
    sig = sign_mod.sign_message(sign_mod.digest_message(FIX / "h1_release_demo.bin"))
    (FIX / "h1_release_demo.bin.sig").write_text(
        base64.b64encode(sig).decode() + "\n", encoding="utf-8")

    # SBOM from the real lockfile (generator is shared with `make gen-h1-sbom`).
    sbom_text = json.dumps(
        sbom_mod.build_sbom(LOCK.read_text(encoding="utf-8")),
        indent=2, sort_keys=True) + "\n"
    SBOM.write_text(sbom_text, encoding="utf-8")

    vectors = {
        "format": "AURALITE-SUPPLY-CHAIN-VECTORS-V1",
        "toolchain": {"channel": "1.99.1"},
        "lock": {
            "packages": LOCK.read_text(encoding="utf-8").count("[[package]]"),
            "git_sources": LOCK.read_text(encoding="utf-8").count('source = "git'),
            "sha256": sha256_file(LOCK),
        },
        "sbom": {"components": len(sbom_mod.build_sbom(
            LOCK.read_text(encoding="utf-8"))["components"]),
                 "sha256": sha256_file(SBOM)},
        "advisories_sha256": sha256_file(FIX / "h1_advisories.json"),
        "release_pubkey_hex": sign_mod.public_key().hex(),
        "demo_sig": {
            "artifact_sha256": sha256_file(FIX / "h1_release_demo.bin"),
            "sig_b64": base64.b64encode(sig).decode(),
        },
        "secret_rules": [rid for rid, _, _ in __import__(
            "tools.scan_secrets", fromlist=["RULES"]).RULES],
        "verdicts": [
            {"case": "toolchain_pinned", "expect": "allow"},
            {"case": "toolchain_unpinned_denied", "expect": "deny",
             "message_contains": "toolchain not pinned"},
            {"case": "clean_lock_allowed", "expect": "allow"},
            {"case": "vulnerable_lock_denied", "expect": "deny",
             "message_contains": "denied RUSTSEC-TEST-0001 (demo-vulnerable v0.9.0)"},
            {"case": "lock_digest_mismatch_denied", "expect": "deny",
             "message_contains": "lockfile digest mismatch"},
            {"case": "sbom_matches", "expect": "allow"},
            {"case": "sbom_drift_denied", "expect": "deny",
             "message_contains": "sbom drift"},
            {"case": "planted_secret_detected", "expect": "deny",
             "message_contains": "secret rule password-assignment matched"},
            {"case": "clean_text_no_secret", "expect": "allow"},
            {"case": "pem_block_detected", "expect": "deny",
             "message_contains": "secret rule private-key-block matched"},
            {"case": "signature_verifies", "expect": "allow"},
            {"case": "forged_signature_denied", "expect": "deny",
             "message_contains": "bad signature"},
        ],
    }
    out = FIX / "h1_supply_chain_vectors.json"
    out.write_text(json.dumps(vectors, indent=2, sort_keys=True) + "\n",
                   encoding="utf-8")
    print(f"wrote tools/fixtures/h1_supply_chain_vectors.json "
          f"({len(vectors['verdicts'])} verdicts, {vectors['lock']['packages']} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
