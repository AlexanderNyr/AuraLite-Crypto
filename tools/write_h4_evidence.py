#!/usr/bin/env python3
"""Write docs/evidence/h4/ (docs/h4-property-plan.md §5).

Self-contained bundle: property-test results, the recorded campaign
(copied from /home/user/h4-campaign), mutation-control log, gates,
inventory (cumulative TOTAL: 454) and SHA256SUMS (repo-relative paths).
The campaign is a recorded artifact of `make property-h4-full`; this script
integrates it and refuses to run without it.
"""
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/evidence/h4"
CAMPAIGN_DIR = Path("/home/user/h4-campaign")

TESTS = [
    ["cargo", "test", "--locked", "-p", "aura-testkit", "--test", "h4_properties"],
    ["cargo", "test", "--locked", "-p", "aura-state", "--test", "h4_tree"],
    ["cargo", "test", "--locked", "-p", "aura-exec", "--test", "h4_model_vm"],
]


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> int:
    if not (CAMPAIGN_DIR / "result.json").exists():
        print("missing recorded campaign: run `make property-h4-full` first")
        return 2
    OUT.mkdir(parents=True, exist_ok=True)

    # 1. Property tests (fast, incremental).
    outputs = []
    tests_ok = True
    for cmd in TESTS:
        run = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        outputs.append((cmd[-1], run.stdout.strip()))
        if run.returncode != 0 or "test result: ok" not in run.stdout:
            tests_ok = False

    # 2. Mutation controls (reuse a complete nc.log, rerun when missing).
    nc_log = OUT / "nc.log"
    if nc_log.exists() and "H4 controls: 6/6 PASS" in nc_log.read_text():
        nc_ok = True
        nc_text = nc_log.read_text()
    else:
        nc = subprocess.run(
            [sys.executable, "tools/nc_h4.py"], cwd=ROOT, capture_output=True, text=True
        )
        nc_text = nc.stdout + nc.stderr
        nc_log.write_text(nc_text)
        nc_ok = nc.returncode == 0 and "H4 controls: 6/6 PASS" in nc_text

    # 3. Recorded campaign (self-contained copy).
    campaign = json.loads((CAMPAIGN_DIR / "result.json").read_text())
    camp_out = OUT / "campaign"
    if camp_out.exists():
        shutil.rmtree(camp_out)
    shutil.copytree(CAMPAIGN_DIR, camp_out)
    summary = campaign.get("summary", {})
    runs = campaign.get("runs", [])
    failures = summary.get("failures", 0)
    clean = failures == 0 and len(runs) == 5
    named = "H4-NC1 PASS" in nc_text and "injected bug -> property finds it" in nc_text
    gate_run = any(row.get("step") == "property-1m" and row.get("exit") == 0 for row in runs)
    diff_runs = [row for row in runs if row.get("step") in ("python-check-rust", "rust-check-python")]
    diff_ok = len(diff_runs) == 2 and all(row.get("exit") == 0 for row in diff_runs)

    check = [
        "# H4 check (generated by tools/write_h4_evidence.py)",
        f"property tests: {'PASS' if tests_ok else 'FAIL'} (3 suites)",
        f"campaign schedule: {summary.get('schedule')}",
        f"campaign txs requested: {summary.get('txs')}",
        f"campaign txs executed: {summary.get('txs', '?')} (see campaign/logs/property-1m.run.log)",
        f"campaign committed: {summary.get('committed', '?')}",
        f"campaign rejected: {summary.get('rejected', '?')}",
        f"campaign sum_checks: {summary.get('sum_checks', '?')}",
        f"campaign final_total: {summary.get('final_total', '?')}",
        f"campaign digest: {summary.get('digest', '?')}",
        f"conservation gate: {'PASS' if gate_run and failures == 0 else 'FAIL'}",
        f"cross-language differential: {'PASS' if diff_ok else 'FAIL'} (both directions)",
        f"named control (injected bug -> property finds it): {'present' if named else 'MISSING'}",
        "test outputs:",
    ]
    for name, output in outputs:
        check.append(f"--- {name}")
        check.append(output)
    (OUT / "check.log").write_text("\n".join(check) + "\n")

    gates = [
        "# H4 gates",
        f"property tests: {'PASS' if tests_ok else 'FAIL'} (3 suites)",
        f"1M-tx conservation ({summary.get('schedule')} recorded): "
        f"{'PASS' if gate_run and failures == 0 else 'FAIL'} "
        f"({summary.get('sum_checks', '?')} checks)",
        f"cross-language differential: {'PASS' if diff_ok else 'FAIL'}",
        f"named control (injected bug -> property finds it): {'PASS' if named else 'FAIL'}",
        f"mutation controls: {'PASS' if nc_ok else 'FAIL'} (6/6)",
    ]
    (OUT / "gates.txt").write_text("\n".join(gates) + "\n")

    inventory = [
        "# H4 inventory (generated by tools/write_h4_evidence.py)",
        "property_suites=3",
        "reference_impls=python-c4-tx,python-s1-tree,naive-rust-model",
        f"campaign_schedule={summary.get('schedule')}",
        f"campaign_txs={summary.get('txs')}",
        f"campaign_committed={summary.get('committed')}",
        f"campaign_rejected={summary.get('rejected')}",
        f"campaign_sum_checks={summary.get('sum_checks')}",
        f"campaign_digest={summary.get('digest')}",
        "named_control=injected_bug_property_finds_it=present",
        "TOTAL: 454 negative controls",
    ]
    (OUT / "inventory.txt").write_text("\n".join(inventory) + "\n")

    report = [
        "# H4 evidence report (property / differential)",
        "",
        f"Recorded campaign `{summary.get('schedule')}`: "
        f"{summary.get('txs')} generated txs, each signed, verified and",
        "canonical-round-tripped; `sum(balances)` checked after every one",
        f"({summary.get('sum_checks')} checks, final total "
        f"{summary.get('final_total')}, digest {summary.get('digest')}).",
        "",
        "Cross-language differential both ways: Rust dump checked by the",
        "Python reference (C4 tx encoder + S1 tree), Python cases checked by",
        "the Rust binary (`campaign/logs/` holds the four differential logs).",
        "",
        "Deviation (plan §3): the gate is `--txs 1000000` (`make",
        "property-h4-full`); this workspace records the schedule named above",
        "with exact counts — no extrapolation.",
        "",
        "Mutation controls: 6/6 (`tools/nc_h4.py`, log in `nc.log`); the",
        "named control injects a conservation bug and the property finds it.",
    ]
    (OUT / "report.md").write_text("\n".join(report) + "\n")

    names = ["check.log", "nc.log", "gates.txt", "inventory.txt", "report.md"]
    names += sorted(str(p.relative_to(OUT)) for p in camp_out.rglob("*") if p.is_file())
    names = [f"docs/evidence/h4/{name}" for name in names]
    names += [
        "docs/h4-property-plan.md",
        "tools/h4_property_campaign.py",
        "tools/h4_reference.py",
        "tools/nc_h4.py",
        "tools/write_h4_evidence.py",
        "tools/gen_c4_vectors.py",
        "crates/aura-testkit/tests/h4_properties.rs",
        "crates/aura-testkit/src/bin/h4-properties.rs",
        "crates/aura-exec/tests/h4_model_vm.rs",
        "crates/aura-state/tests/h4_tree.rs",
    ]
    sums = [f"{sha256_file(ROOT / name)}  {name}" for name in names]
    (OUT / "SHA256SUMS").write_text("\n".join(sums) + "\n")

    ok = tests_ok and nc_ok and clean and named and diff_ok
    print(
        f"evidence-h4: tests={tests_ok} nc={nc_ok} campaign_clean={clean} "
        f"named={named} differential={diff_ok}"
    )
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
