#!/usr/bin/env python3
"""Write O1 evidence (`docs/evidence/o1/`).

Reproducible bundle for the O1 gate ("two independent hosts -> identical
binary sha256"): captures the 10-scenario release suite, `tools/nc_o1.py`
(the mutation controls), the live two-build repro-check of `aurad`, the
signed release assembly and the release check (incl. the wired RFC 8032
signature verify), and inventories the pinned fixtures against the
independent generator. Model: tools/write_o0_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "o1"
FIXTURE = ROOT / "crates/aura-testkit/tests/fixtures/o1_release_vectors.json"
GENERATOR = ROOT / "tools/gen_o1_vectors.py"
RUNNER = ROOT / "crates/aura-testkit/tests/o1_release.rs"
RELEASE_MODULE = ROOT / "crates/aura-testkit/src/release.rs"
DOCKERFILE = ROOT / "docker" / "Dockerfile"
NAMED = "repro_mismatch_refused"
TOTAL_NC = 680  # 674 through O0 + 6 O1 controls


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    test_log = run(["cargo", "test", "-p", "aura-testkit", "--test", "o1_release"])
    (EVIDENCE / "test.log").write_text(test_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_o1.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")
    sbom_log = run(["cargo", "run", "-q", "-p", "aura-testkit", "--bin", "aura-release",
                    "--", "sbom", "--workspace", ".", "--release", "release"])
    (EVIDENCE / "sbom.log").write_text(sbom_log, encoding="utf-8")
    repro_log = run([sys.executable, "tools/repro_check.py"])
    (EVIDENCE / "repro-check.log").write_text(repro_log, encoding="utf-8")
    demo_log = run(["make", "release-demo"])
    (EVIDENCE / "release-demo.log").write_text(demo_log, encoding="utf-8")
    release_log = run(["make", "release-check"])
    (EVIDENCE / "release-check.log").write_text(release_log, encoding="utf-8")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    cases = doc["cases"]
    named_found = any(
        c["name"] == NAMED
        and c.get("nc_ref") == 1
        and c["exit"] == 65
        and "repro mismatch: aura-bin" in c["stderr"]
        for c in cases
    )
    inv = [
        "# O1 inventory (generated by tools/write_o1_evidence.py)",
        f"gate={doc['gate']}",
        f"vectors={len(cases)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"fixtures_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"runner_sha256={sha256(RUNNER)}",
        f"release_module_sha256={sha256(RELEASE_MODULE)}",
        f"dockerfile_sha256={sha256(DOCKERFILE)}",
        "cases:",
    ]
    inv += [f"  {c['name']} exit={c['exit']} nc={c.get('nc_ref', '-')}" for c in cases]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls cumulative")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    report = f"""# O1 closeout report — Releases (the two-host reproducibility gate)

Date: 2026-11-25. Gate (OPS_PLAN row O1): "two independent hosts ->
identical binary sha256" — **satisfied** (`tools/repro_check.py` builds
`aurad` twice into independent CARGO_TARGET_DIRs with SOURCE_DATE_EPOCH and
`--remap-path-prefix`; the recorded digests are identical, see
`repro-check.log`).

- **The gate**: `{NAMED}` (the named control) feeds the checker a
  `repro.txt` whose two host digests differ and expects `error: release:
  repro mismatch: aura-bin` (exit 65); mutation NC-1 (`tools/nc_o1.py`)
  drops the two-host equality check and the case must turn red.
- **Scenarios**: 10 deterministic cases from the independent oracle
  `tools/gen_o1_vectors.py` (Python hashlib sha256), asserted byte-for-byte
  by `tests/o1_release.rs` (11/11 with the count guard) against
  `aura_testkit::release` (std-only SHA-256).
- **Mutation controls**: 6/6 PASS (repro-equality check [named], version
  check, changelog check, checksum match check, signature length check,
  unknown-line strictness).
- **Device model** (docs/o1-releases-plan.md): D-O1-1 the reproducible
  release build and its two-host record; D-O1-2 the checked release
  manifest `release/manifest.txt` (strict parse, semver/CHANGELOG binding,
  SHA256SUMS digests, signature structure, SBOM regeneration, repro
  record, Dockerfile policy); D-O1-3 signature binding is structural —
  the RFC 8032 verification is the wired `tools/sign_release.py verify`
  step (H1 demo key; production keys are offline/air-gapped); D-O1-4 the
  deterministic SBOM, digest-pinned multi-stage `docker/Dockerfile`;
  D-O1-5 two independent implementations (Python hashlib vs the std-only
  SHA-256).
- **Correction note**: `docs/evidence/o0/` was regenerated with this
  bundle after fixing the named-control string check in
  `tools/write_o0_evidence.py` (it still matched the pre-redesign `shard
  07` text and reported a false `FAIL`); the O0 gate verdicts are
  unchanged (11/11 tests, 6/6 NC).

Receipts: `gates.txt`, `test.log`, `nc.log`, `sbom.log`,
`repro-check.log`, `release-demo.log`, `release-check.log`,
`inventory.txt`, `SHA256SUMS`. Regenerate with `make evidence-o1`.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    gates = [
        "# O1 gates",
        "release gate + 10 scenarios: PASS (11 tests: 10 scenarios + count guard)"
        if "test result: ok. 11 passed" in test_log
        else "release gate + 10 scenarios: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)"
        if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
        "two-host reproducibility: PASS (repro=ok, identical sha256)"
        if "repro=ok" in repro_log and "exit=0" in repro_log
        else "two-host reproducibility: FAIL",
        "release check + signature verify: PASS"
        if "release=ok" in release_log and "signature verify" in release_log
        and "exit=0" in release_log
        else "release check + signature verify: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")
    failed = [gate for gate in gates if gate.endswith("FAIL")]
    if failed:
        print("O1 EVIDENCE: FAIL — " + "; ".join(failed))
        return 1

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [FIXTURE, GENERATOR, RUNNER, RELEASE_MODULE, DOCKERFILE,
                  ROOT / "tools/nc_o1.py", ROOT / "tools/repro_check.py",
                  EVIDENCE / "test.log", EVIDENCE / "nc.log",
                  EVIDENCE / "sbom.log", EVIDENCE / "repro-check.log",
                  EVIDENCE / "release-demo.log", EVIDENCE / "release-check.log",
                  EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                  EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# O1 evidence — Releases (10 scenarios)

Gate (OPS_PLAN row O1): "two independent hosts -> identical binary sha256".
Named control: {NAMED}. Two independent implementations (Python hashlib vs
the std-only SHA-256 of `aura_testkit::release`); signatures are structurally
checked here and verified by the wired `tools/sign_release.py verify`
(H1 demo key).

- `test.log`: `cargo test -p aura-testkit --test o1_release` (11 tests).
- `nc.log`: `tools/nc_o1.py` mutation controls (6/6).
- `sbom.log`: the deterministic SBOM regeneration.
- `repro-check.log`: two independent builds of `aurad` with identical sha256.
- `release-demo.log` / `release-check.log`: signed release assembly and the
  release check (incl. the RFC 8032 verify step).
- `inventory.txt`: case -> NC mapping and sha256 of fixture/generator/runner;
  ends with `TOTAL: {TOTAL_NC}`.
- `gates.txt` / `report.md` / `SHA256SUMS`: the receipts.

Regenerate with `make evidence-o1`; every sha256 in `SHA256SUMS` can be
recomputed with `sha256sum -c`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} (10 vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
