#!/usr/bin/env python3
"""Write H2 evidence (`docs/evidence/h2/`).

Reproducible bundle for the H2 gate ("50 crypto vectors + side-channel
checklist"): captures `tools/gen_h2_vectors.py --check` (oracle drift),
`tools/check_h2_review.py` (checklist gate), `cargo test -p aura-crypto
--test h2_crypto` (the 50 vectors) and `tools/nc_h2.py` (mutation controls).
Model: tools/write_h1_evidence.py.
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

EVIDENCE = ROOT / "docs" / "evidence" / "h2"
FIX = ROOT / "tools" / "fixtures"
VECTORS = ROOT / "crates" / "aura-crypto" / "tests" / "fixtures" / "h2_vectors.txt"
NAMED = "shared_domain"
TOTAL_NC = 442  # 436 through H1 + 6 H2 controls


def sha256(path: Path) -> str:
    import hashlib
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def vector_kinds() -> dict[str, int]:
    kinds: dict[str, int] = {}
    for line in VECTORS.read_text(encoding="utf-8").splitlines():
        if line.startswith("kind="):
            kinds[line[5:]] = kinds.get(line[5:], 0) + 1
    return dict(sorted(kinds.items()))


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    check_log = (run([sys.executable, "tools/gen_h2_vectors.py", "--check"])
                 + run([sys.executable, "tools/check_h2_review.py"])
                 + run(["cargo", "test", "-p", "aura-crypto", "--test", "h2_crypto"]))
    (EVIDENCE / "check.log").write_text(check_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_h2.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")

    checklist = json.loads((FIX / "h2_review_checklist.json").read_text(encoding="utf-8"))
    kinds = vector_kinds()
    total = sum(kinds.values())
    named_found = "PASS NC: shared domain -> signature passes, suite red" in nc_log
    inv = [
        "# H2 inventory (generated by tools/write_h2_evidence.py)",
        f"vectors={total}",
        "vector_kinds:",
    ]
    inv += [f"  {name}={count}" for name, count in kinds.items()]
    inv += [
        f"checklist_items={len(checklist['items'])}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        "checklist:",
    ]
    inv += [f"  {item['id']} status={item['status']} owner={item['owner']}"
            for item in checklist["items"]]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    report = f"""# H2 closeout report — crypto review

Date: 2026-11-14. Gate (SECURITY_PLAN row H2): "50 crypto vectors +
side-channel checklist; NC: shared domain -> signature passes, red" —
**satisfied**.

- **Vectors**: {total} golden crypto vectors from the independent oracle
  `tools/gen_h2_vectors.py` (pure-Python RFC 8032, python blake3, from-spec
  `domain_message`): keygen, sign/verify byte-for-byte, wrong domain, cross
  chain, tampered payload, wrong key, high-S malleation, digest layout,
  edge payloads. `crates/aura-crypto/tests/h2_crypto.rs` asserts every
  expectation (`h2_vector_count_is_50` pins the count).
- **Malleability (D-H2-3)**: `verify_raw` rejects `S >= L` with the distinct
  `CryptoError::NonCanonicalSignature`. Review finding: the classic twin
  `(R, S+L)` satisfies the same verification equation; ed25519-dalek 2.2.0's
  default `check_scalar` rejects it, but its `legacy_compatibility` feature
  reopens malleation ("permits signature malleability" — dalek's own
  comment). The guard makes `S < L` our own invariant.
- **Side-channel checklist (D-H2-4)**: 10 machine-readable items
  (`### H2-SCxx`, `Claim/Owner/Evidence/Status`) pinned by
  `tools/fixtures/h2_review_checklist.json`, re-derived by
  `tools/check_h2_review.py`, which also greps the reviewed sources for each
  claim (constant-time compare, Zeroizing, Debug redaction, S<L guard, five
  domain tags, chain binding, length prefixes, hash context).
- **Post-quantum (D-H2-5)**: ML-DSA (FIPS 204) primary, SLH-DSA (FIPS 205)
  stateless backup; hybrid `Ed25519 || ML-DSA` migration planned for
  W1-FORMAT-v2 / Stage 2 (plan §4).
- **Named control** ({NAMED}): `tools/nc_h2.py` NC-1 collapses every
  `Domain::tag()` to one tag and requires the h2 suite to go red with
  `H2: wrong-domain signature must be rejected`.
- **Mutation controls: 6/6 PASS** (shared domain, canonical-S guard, chain
  binding, checklist owner, checklist evidence, checklist status).

Receipts: `gates.txt`, `check.log`, `nc.log`, `inventory.txt`, `SHA256SUMS`.
Regenerate with `make evidence-h2`. Public project material only.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    checklist_ok = "CRYPTO REVIEW: OK" in check_log
    vectors_ok = f"test result: ok" in check_log and "h2_vector_count_is_50 ... ok" in check_log
    oracle_ok = "ORACLE: OK" in check_log and "DRIFT" not in check_log
    gates = [
        "# H2 gates",
        f"crypto vectors: {'PASS' if vectors_ok else 'FAIL'} ({total}/50)",
        f"oracle drift: {'none' if oracle_ok else 'DRIFT'}",
        f"side-channel checklist: {'PASS' if checklist_ok else 'FAIL'} "
        f"({len(checklist['items'])} items)",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)" if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")

    sources = [FIX / "h2_review_checklist.json", VECTORS,
               ROOT / "docs" / "h2-crypto-review-plan.md",
               ROOT / "tools" / "gen_h2_vectors.py",
               ROOT / "tools" / "check_h2_review.py",
               ROOT / "tools" / "nc_h2.py",
               ROOT / "crates" / "aura-crypto" / "src" / "ed25519.rs",
               ROOT / "crates" / "aura-crypto" / "src" / "hash.rs",
               ROOT / "crates" / "aura-crypto" / "src" / "secret.rs",
               ROOT / "crates" / "aura-crypto" / "src" / "error.rs",
               ROOT / "crates" / "aura-crypto" / "tests" / "h2_crypto.rs",
               ROOT / "crates" / "aura-types" / "src" / "primitives.rs"]
    sums = [f"{sha256(p)}  {p.relative_to(ROOT)}" for p in sources if p.exists()]
    sums += [f"{sha256(p)}  {p.relative_to(ROOT)}"
             for p in [EVIDENCE / "check.log", EVIDENCE / "nc.log",
                       EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                       EVIDENCE / "report.md"]]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# H2 evidence — crypto review ({total} vectors)

Gate (SECURITY_PLAN row H2): "50 crypto vectors + side-channel checklist;
NC: shared domain -> signature passes, red".

- `check.log` — oracle drift check, `tools/check_h2_review.py` and the h2
  vector suite (`crates/aura-crypto/tests/h2_crypto.rs`).
- `nc.log` — `tools/nc_h2.py` mutation controls (6), named = shared domain.
- `inventory.txt` — vector kinds, checklist statuses and the cumulative NC
  total ({TOTAL_NC}).
- `report.md`, `gates.txt`, `SHA256SUMS`.

Regenerate: `make gen-h2-vectors`, `make evidence-h2`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} ({total} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
