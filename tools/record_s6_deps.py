#!/usr/bin/env python3
"""Record the S6 dependency delta (none — state sync uses existing crates).

The C3 baseline is frozen historical evidence. S6 adds NO external crate: the
state-sync protocol uses `aura-codec`, `aura-crypto`, `aura-types` and the S4
`snapshot` module, all already present. `sha2` was already promoted to a direct
dep in S4.

Usage:
    python3 tools/record_s6_deps.py
    make record-s6-deps
"""
from __future__ import annotations

import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "evidence" / "s6-dependency-addendum.txt"


def read_pairs(path: Path) -> set[tuple[str, str]]:
    out = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            name, version = line.split("=", 1)
            out.add((name, version))
    return out


def main() -> int:
    data = tomllib.loads((REPO / "Cargo.lock").read_text(encoding="utf-8"))
    current = {
        (p["name"], p["version"])
        for p in data.get("package", [])
        if "source" in p
    }
    known = read_pairs(REPO / "docs" / "spec" / "c3-dependency-allowlist.txt")
    for path in (REPO / "docs" / "spec").glob("*-dependency-addendum.txt"):
        known |= read_pairs(path)
    for path in (REPO / "docs" / "evidence").glob("*-dependency-addendum.txt"):
        if path != OUT:
            known |= read_pairs(path)
    missing = sorted(current - known)
    if missing:
        print(f"ERROR: unrecorded crates: {missing}")
        return 1
    OUT.write_text(
        "\n".join([
            "# AuraLite-Crypto external dependency addendum (S6).",
            "# Generated by tools/record_s6_deps.py from Cargo.lock.",
            "# S6 pruning/archive uses only existing workspace crates and modules.",
            "# No new external crate, no new workspace crate in this phase.",
            "# Build-profile note: [profile.dev.package.blake3] and",
            "# [profile.dev.package.sha2] are opt-level = 3 in the workspace",
            "# Cargo.toml (measured: blake3 5.785 us -> 0.178 us per hash in a",
            "# debug build). Versions are unchanged; only optimisation level.",
        ]) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(REPO)} (0 new crates)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
