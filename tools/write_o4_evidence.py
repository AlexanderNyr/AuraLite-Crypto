#!/usr/bin/env python3
"""Write O4 evidence (`docs/evidence/o4/`).

Reproducible bundle for the O4 gate ("30 days, >= 99% uptime, >= 100 000
txs, 0 unfixed criticals" — OPS_PLAN row O4): captures the 12-scenario
public-testnet suite, `tools/nc_o4.py` (the mutation controls), the
measured receipts (`aurad-testnet`: the scripted 30-day public schedule
on the real pipeline with 140 transfers per poll, the ten-validator
window and the bug-bounty triage journal), the independent ledger
cross-checks (`aura-testnet metrics`, `aura-testnet triage`), and the
public service surface (`aurad-faucet`, `aurad-explorer`). Model:
tools/write_o3_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "o4"
FIXTURE = ROOT / "crates/aura-testkit/tests/fixtures/o4_testnet_public_vectors.json"
GENERATOR = ROOT / "tools/gen_o4_vectors.py"
RUNNER = ROOT / "crates/aura-testkit/tests/o4_testnet_public.rs"
TESTNET_MODULE = ROOT / "crates/aura-testkit" / "src" / "testnet.rs"
MEASURER_BIN = ROOT / "crates/aura-node" / "src" / "bin" / "aurad-testnet.rs"
FAUCET_BIN = ROOT / "crates/aura-node" / "src" / "bin" / "aurad-faucet.rs"
EXPLORER_BIN = ROOT / "crates/aura-node" / "src" / "bin" / "aurad-explorer.rs"
PLAN = ROOT / "docs" / "o4-testnet-public-plan.md"
GUIDE = ROOT / "docs" / "testnet-public.md"
BOUNTY = ROOT / "docs" / "testnet-bounty.md"
JOURNAL_SOURCE = ROOT / "tools" / "fixtures" / "h8_findings.json"
NAMED = "unfixed_criticals_refused"
TOTAL_NC = 699  # 692 through O3 + 7 O4 controls


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    test_log = run(["cargo", "test", "-p", "aura-testkit", "--test", "o4_testnet_public"])
    (EVIDENCE / "test.log").write_text(test_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_o4.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")
    receipts_log = run(["make", "testnet-receipts"])
    (EVIDENCE / "receipts.log").write_text(receipts_log, encoding="utf-8")
    check_log = run(["make", "testnet-check"])
    (EVIDENCE / "testnet-check.log").write_text(check_log, encoding="utf-8")
    summary_log = run(
        ["cargo", "run", "-q", "-p", "aura-testkit", "--bin", "aura-testnet",
         "--", "summary", "--receipts", "release/testnet.txt"]
    )
    (EVIDENCE / "summary.log").write_text(summary_log, encoding="utf-8")

    # The public service surface (D-O4-5): faucet and explorer over the
    # node RpcBackend (the make target writes its sample inputs).
    surface_log = run(["make", "testnet-public-surface"])
    (EVIDENCE / "public-surface.log").write_text(surface_log, encoding="utf-8")

    measured = ROOT / "release" / "testnet.txt"
    ledger = ROOT / "release" / "metrics-30d.txt"
    journal = ROOT / "release" / "triage.txt"
    shutil.copyfile(measured, EVIDENCE / "testnet.txt")
    shutil.copyfile(ledger, EVIDENCE / "metrics-30d.txt")
    shutil.copyfile(journal, EVIDENCE / "triage.txt")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    cases = doc["cases"]
    named_found = any(
        c["name"] == NAMED
        and c.get("nc_ref") == 1
        and c["exit"] == 65
        and "criticals: 1" in c["stderr"]
        for c in cases
    )
    inv = [
        "# O4 inventory (generated by tools/write_o4_evidence.py)",
        f"gate={doc['gate']}",
        f"vectors={len(cases)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"fixtures_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"runner_sha256={sha256(RUNNER)}",
        f"testnet_module_sha256={sha256(TESTNET_MODULE)}",
        f"measurer_bin_sha256={sha256(MEASURER_BIN)}",
        f"faucet_bin_sha256={sha256(FAUCET_BIN)}",
        f"explorer_bin_sha256={sha256(EXPLORER_BIN)}",
        f"plan_sha256={sha256(PLAN)}",
        f"guide_sha256={sha256(GUIDE)}",
        f"bounty_sha256={sha256(BOUNTY)}",
        f"journal_source_sha256={sha256(JOURNAL_SOURCE)}",
        f"receipt_sha256={sha256(EVIDENCE / 'testnet.txt')}",
        f"metrics_sha256={sha256(EVIDENCE / 'metrics-30d.txt')}",
        f"triage_sha256={sha256(EVIDENCE / 'triage.txt')}",
        "cases:",
    ]
    inv += [f"  {c['name']} exit={c['exit']} nc={c.get('nc_ref', '-')}" for c in cases]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls cumulative")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    receipt_text = (EVIDENCE / "testnet.txt").read_text(encoding="utf-8")
    report = f"""# O4 closeout report — public testnet (M2) window and public surface

Date: 2026-11-27. Gate (OPS_PLAN row O4): "30 days, >= 99% uptime, >=
100 000 txs, 0 unfixed criticals" — **satisfied on measured receipts**
(`testnet.txt` above; `aurad-testnet` produced these values on the
shipped pipeline: the scripted 30-day public schedule (30 x 24 hourly
polls, 140 transfers per poll = 100 800 transactions — day/hour from the
schedule, heights/roots/tx totals from the live chain), the
ten-validator window and the bug-bounty triage journal).

- **100 800 transactions, 30 days, 100% uptime** (D-O4-2): the
  committed metrics ledger `metrics-30d.txt`; the rollup re-derives
  `metrics ledger: days=30 uptime=100 txs=100800` independently and
  refuses any regressing window (`tx regression at <d> <h>`).
- **0 unfixed criticals** (D-O4-3): the triage journal `triage.txt`
  seeds from the real H8 audit/bounty findings
  (`tools/fixtures/h8_findings.json`); `aura-testnet triage` re-derives
  `triage ledger: items=12 open=3 criticals=0` and refuses an open
  critical-class finding by id (`open critical <id>`). The named gate
  `{NAMED}` feeds the checker a receipt with `criticals 1` and expects
  `error: testnet: criticals: 1` (exit 65); mutation NC-1 drops the
  criticals check and the case must turn red.
- **10 validators** (D-O4-4): `aurad-testnet` opens ten independent
  single-validator pipelines (distinct seeds, one genesis allocation
  set) and records `validators 10` only when all ten genesis state roots
  agree byte-for-byte. External operation is organizational (the O3
  invited-operator method; onboarding via `docs/testnet-public.md`).
- **The public surface** (D-O4-5): `aurad-faucet` (capped payouts
  through the node `RpcBackend::submit_tx`) and `aurad-explorer`
  (`head`/`block`/`tx`/`balance` queries through
  `get_block`/`get_tx`/`get_balance`) — exercised in
  `public-surface.log`; `docs/testnet-public.md` is the public guide and
  `docs/testnet-bounty.md` the bounty policy (H8 program inherited).
- **Scenarios**: 12 deterministic cases from the independent oracle
  `tools/gen_o4_vectors.py`, asserted byte-for-byte by
  `tests/o4_testnet_public.rs` (13 tests: 12 scenarios + the count
  guard) against `aura_testkit::testnet`: the gate pass and pinned
  summary, the five gate refusals (days/uptime/validators/txs/criticals
  [named]), the foreign-line refusal, and the two ledger pairs (metrics
  pass + `tx regression at 3 2`; triage pass + `open critical T-0002`).
- **Mutation controls**: 7/7 PASS (criticals [named], days, uptime,
  validators, txs, metrics regression, triage open-critical).

Measured receipt (testnet.txt):

```
{receipt_text}```

Receipts: `gates.txt`, `test.log`, `nc.log`, `receipts.log`,
`testnet-check.log`, `summary.log`, `public-surface.log`, `testnet.txt`,
`metrics-30d.txt`, `triage.txt`, `inventory.txt`, `SHA256SUMS`.
Regenerate with `make evidence-o4`.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    receipt_ok = (
        "testnet=ok uptime=ok validators=ok txs=ok criticals=ok" in check_log
        and "metrics ledger: days=30 uptime=100 txs=100800" in check_log
        and "triage ledger: items=12 open=3 criticals=0" in check_log
        and "exit=0" in check_log
    )
    surface_ok = (
        "payout " in surface_log
        and " ok" in surface_log
        and "head height=" in surface_log
        and "exit=0" in surface_log
    )
    gates = [
        "# O4 gates",
        "public testnet gate + 12 scenarios: PASS (13 tests: 12 scenarios + count guard)"
        if "test result: ok. 13 passed" in test_log
        else "public testnet gate + 12 scenarios: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (7/7)"
        if "RESULT: 7/7 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
        "measured receipts + ledger cross-check: PASS (testnet=ok, days=30, txs=100800, criticals=0)"
        if receipt_ok
        else "measured receipts + ledger cross-check: FAIL",
        "public surface (faucet/explorer over RpcBackend) + docs + bounty: PASS"
        if surface_ok
        else "public surface (faucet/explorer over RpcBackend) + docs + bounty: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")
    failed = [gate for gate in gates if gate.endswith("FAIL")]
    if failed:
        print("O4 EVIDENCE: FAIL — " + "; ".join(failed))
        return 1

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [FIXTURE, GENERATOR, RUNNER, TESTNET_MODULE, MEASURER_BIN,
                  FAUCET_BIN, EXPLORER_BIN, PLAN, GUIDE, BOUNTY,
                  JOURNAL_SOURCE, ROOT / "tools/nc_o4.py",
                  EVIDENCE / "test.log", EVIDENCE / "nc.log",
                  EVIDENCE / "receipts.log", EVIDENCE / "testnet-check.log",
                  EVIDENCE / "summary.log", EVIDENCE / "public-surface.log",
                  EVIDENCE / "testnet.txt", EVIDENCE / "metrics-30d.txt",
                  EVIDENCE / "triage.txt", EVIDENCE / "inventory.txt",
                  EVIDENCE / "gates.txt", EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# O4 evidence — public testnet (M2) gate (12 scenarios)

Gate (OPS_PLAN row O4): "30 days, >= 99% uptime, >= 100 000 txs, 0
unfixed criticals". Named control: {NAMED}. The receipts in
`testnet.txt` and the ledgers in `metrics-30d.txt` / `triage.txt` are
measured by `aurad-testnet` (the scripted 30-day public schedule on the
real pipeline, 140 transfers per poll, plus the ten-validator window);
`aura-testnet check/metrics/triage` validate them and independently
re-derive the rollups. `docs/testnet-public.md` and
`docs/testnet-bounty.md` are the public guide and bounty policy.

- `test.log`: `cargo test -p aura-testkit --test o4_testnet_public` (13 tests).
- `nc.log`: `tools/nc_o4.py` mutation controls (7/7).
- `receipts.log`: the measured `aurad-testnet` run (schedule + validators + journal).
- `testnet-check.log`: `aura-testnet check` + `metrics` + `triage`.
- `summary.log`: the pinned normalized report.
- `public-surface.log`: `aurad-faucet` + `aurad-explorer` over the node RpcBackend.
- `testnet.txt` / `metrics-30d.txt` / `triage.txt`: the first O4 receipts
  (committed with the phase).
- `inventory.txt`: case -> NC mapping and sha256 of fixture/generator/
  runner/module/bins/docs; ends with `TOTAL: {TOTAL_NC}`.
- `gates.txt` / `report.md` / `SHA256SUMS`: the receipts.

Regenerate with `make evidence-o4`; every sha256 in `SHA256SUMS` can be
recomputed with `sha256sum -c`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} (12 vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
