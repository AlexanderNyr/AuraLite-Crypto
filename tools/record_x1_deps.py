#!/usr/bin/env python3
"""Record the X1 dependency delta (the first engine dependency).

The C3 baseline is frozen historical evidence, and a phase must not add files to
`docs/spec/` (its index is checksummed C10 evidence), so the delta lands in
`docs/evidence/x1-dependency-addendum.txt`.

X1 adds two external roots:

  * `wasmi =2.0.0` — the DEFAULT engine (deterministic interpreter, portable
    dispatcher). Six crates: wasmi, wasmi_core, wasmi_ir, wasmi_collections,
    wasmparser, spin.
  * `wasmtime =50.0.0` — the OPTIONAL JIT engine behind the
    `wasmtime-engine` feature. Cranelift and friends: a large subtree that the
    default build never compiles, but which `Cargo.lock` must still pin and
    checksum, so it is recorded here in full.

Usage:
    python3 tools/record_x1_deps.py
    make record-x1-deps
"""

from __future__ import annotations

import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "evidence" / "x1-dependency-addendum.txt"

HEADER = """# AuraLite-Crypto external dependency addendum (X1).
# Generated by tools/record_x1_deps.py from Cargo.lock.
# X1 adds the execution engine. Two roots, both exact-pinned and checksummed:
#   wasmi    =2.0.0   -> the DEFAULT backend (deterministic interpreter,
#                        features std + validate + deterministic +
#                        portable-dispatch; SIMD is not compiled in)
#   wasmtime =50.0.0  -> the OPTIONAL backend behind `wasmtime-engine`
#                        (Cranelift JIT; not compiled by the default build)
# Bumping either engine changes fuel metering, so it is a protocol decision
# with its own patch, not a `cargo update`.
# Every crate below is in Cargo.lock with a crates.io source and a sha256.
"""

MARK_WASMI = "# --- ismi/wasmi subtree (default build) ---".replace("ismi/", "")
MARK_WASMTIME = "# --- wasmtime / cranelift subtree (feature `wasmtime-engine` only) ---"


def read_pairs(path: Path) -> set[tuple[str, str]]:
    out: set[tuple[str, str]] = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            name, version = line.split("=", 1)
            out.add((name, version))
    return out


def known_crates() -> set[tuple[str, str]]:
    known = read_pairs(REPO / "docs" / "spec" / "c3-dependency-allowlist.txt")
    for path in (REPO / "docs" / "spec").glob("*-dependency-addendum.txt"):
        known |= read_pairs(path)
    for path in (REPO / "docs" / "evidence").glob("*-dependency-addendum.txt"):
        if path != OUT:
            known |= read_pairs(path)
    return known


def main() -> int:
    data = tomllib.loads((REPO / "Cargo.lock").read_text(encoding="utf-8"))
    current = {
        (p["name"], p["version"]) for p in data.get("package", []) if "source" in p
    }
    new = sorted(current - known_crates())

    wasmi_prefixes = ("wasmi", "wasmparser", "spin", "bitflags", "libm", "smallvec")
    is_wasmi = lambda name: name.startswith(wasmi_prefixes)  # noqa: E731
    wasmi_set = [pair for pair in new if is_wasmi(pair[0])]
    wasmtime_set = [pair for pair in new if pair not in wasmi_set]

    lines = [HEADER.rstrip(), "", MARK_WASMI]
    lines += [f"{name}={version}" for name, version in wasmi_set]
    lines += ["", MARK_WASMTIME]
    lines += [f"{name}={version}" for name, version in wasmtime_set]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(new)} new crates)")
    print(f"  wasmi subtree:    {len(wasmi_set)}")
    print(f"  wasmtime subtree: {len(wasmtime_set)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
