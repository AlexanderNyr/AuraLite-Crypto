#!/usr/bin/env python3
"""Write W2 evidence (`docs/evidence/w2/`).

Reproducible bundle for the W2 gate ("40 CLI vectors, including rejection of a
tx with a foreign chain-id"): captures `make test-w2` (the vector suite),
`tools/nc_w2.py` (the mutation controls), and inventories the pinned fixture
against the independent generator. Model: tools/write_w0_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "w2"
FIXTURE = ROOT / "crates/aura-wallet/tests/fixtures/w2_cli_vectors.json"
GENERATOR = ROOT / "tools/gen_w2_vectors.py"
RUNNER = ROOT / "crates/aura-wallet/tests/w2_cli.rs"
NAMED = "sign_foreign_chain"


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    test_log = run(["cargo", "test", "-p", "aura-wallet", "--features",
                    "insecure-test-kdf", "--test", "w2_cli"])
    (EVIDENCE / "test-w2.log").write_text(test_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_w2.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    cases = doc["cases"]
    named_found = any(
        c["name"] == NAMED
        and c["expect_exit"] == 65
        and any("foreign chain-id" in line for line in c["expect_stderr"])
        for c in cases
    )
    inv = [
        "# W2 inventory (generated by tools/write_w2_evidence.py)",
        f"gate={doc['gate']}",
        f"vectors={len(cases)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"fixtures_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"runner_sha256={sha256(RUNNER)}",
        "cases:",
    ]
    inv += [f"  {c['name']} exit={c['expect_exit']}" for c in cases]
    inv.append("TOTAL: 412 negative controls")  # 406 through W1 + 6 W2 controls
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    gates = [
        "# W2 gates",
        "40 CLI vectors: PASS (42 tests: 40 vectors + count-guard + replay gate)"
        if "test result: ok. 42 passed" in test_log
        else "40 CLI vectors: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)" if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")

    report = f"""# W2 closeout report — `aura-wallet` CLI

Date: 2026-11-11. Gate (WALLET_PLAN row W2): "40 CLI vectors, including
rejection of a tx with a foreign chain-id" — **satisfied**.

- **Vectors**: 40 CLI cases generated by the independent oracle
  `tools/gen_w2_vectors.py` (BIP-39, SLIP-0010, bech32, C4 wire encoder,
  BLAKE3, Ed25519; self-checked against RFC 8032 and the W1 pinned identity),
  asserted byte-for-byte (exit code + both streams) by `tests/w2_cli.rs`:
  42/42 green under `--features insecure-test-kdf`.
- **Named control**: `sign_foreign_chain` — a tx carrying a foreign chain-id is
  refused before signing (`error: foreign chain-id: tx=evil-net-9,
  wallet=auralite-test-1`, exit 65). A mutation that drops the check turns this
  test red (`tools/nc_w2.py` NC-1).
- **Mutation controls**: 6/6 PASS (chain-id accepted, ballot chain binding
  dropped, password echoed, broadcast signature verification skipped, stake
  payload order swapped, nonce replay accepted).
- **Replay gate**: `broadcast_replay_refused` — the same signed transfer is
  accepted once and refused at the next height (nonce mismatch, exit 69).
- **Design decisions** (docs/w2-cli-plan.md): D-W2-1 file ledger behind the
  `Ledger` trait; D-W2-2 Ed25519 wallet ballots (B9 votes are BLS); D-W2-3
  canonical `wallet-stake-v1` payload; D-W2-4 secrets only via files.

Receipts: `gates.txt`, `test-w2.log`, `nc.log`, `inventory.txt`, `SHA256SUMS`.
Regenerate with `make evidence-w2`. Public test data only — never use for funds.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [FIXTURE, GENERATOR, RUNNER,
                  ROOT / "tools/nc_w2.py", ROOT / "crates/aura-wallet/src/cli.rs",
                  EVIDENCE / "test-w2.log", EVIDENCE / "nc.log",
                  EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                  EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# W2 evidence — `aura-wallet` CLI (40 CLI vectors)

Gate (WALLET_PLAN row W2): "40 CLI vectors, including rejection of a tx with a
foreign chain-id". All fixtures are PUBLIC TEST DATA ONLY — never use for funds.

- `test-w2.log` — `cargo test --features insecure-test-kdf --test w2_cli`:
  {len(cases)} vectors plus `vectors_file_has_exactly_40_unique_cases` and
  `broadcast_replay_refused`, byte-for-byte against the independent oracle.
- `nc.log` — `tools/nc_w2.py` mutation controls (6): each source mutation must
  turn its named test red; compilation failure is not a valid red.
- `inventory.txt` — the 40 cases with exit codes, the named control, and the
  SHA-256 pin of the fixture, generator and runner.
- `gates.txt` — gate summary.
- `SHA256SUMS` — digests of the deliverables and evidence files.

The vectors are produced by `tools/gen_w2_vectors.py` (pure Python: BIP-39,
SLIP-0010, bech32, C4 wire encoder, BLAKE3, Ed25519; self-checked against
RFC 8032 and the W1 pinned identity). Regenerate with `make gen-w2-vectors`;
rebuild this bundle with `make evidence-w2`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")

    print(f"wrote {EVIDENCE.relative_to(ROOT)} ({len(cases)} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
