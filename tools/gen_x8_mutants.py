#!/usr/bin/env python3
"""Generate the X8 mutant corpus: 100 damaged modules, each with its expected verdict.

The verifier must reject **everything** it is supposed to reject and accept every
shipped artifact. Proving only the second half is easy; the corpus exists so the
first half is measured too.

The mutants are produced *independently* of the Rust verifier — this file has its own
WASM walker — so the gate compares two implementations rather than one implementation
with itself. Twelve kinds of damage, cycled over the six shipped artifacts:

  magic           flip one magic byte                  -> bad_magic
  version         claim version 2                      -> bad_version
  float_type      a parameter type becomes f32         -> float_type
  float_local     a declared local becomes f64         -> float_type
  import          a module name becomes WASI           -> import_not_allowed
  global_type     a global becomes f32                 -> global_type
  memory_max      the memory maximum exceeds the cap   -> memory_limits
  opcode          an integer opcode becomes f32.add    -> opcode_banned
  call_index      a `call` names a function that is not there -> call_index
  local_index     a `local.get` names a local that is not there -> local_index
  label_depth     a `br_if` branches past the outermost label -> label_depth
  export_shape    the `run` export is renamed          -> export_shape
  function_code   the function section claims one function too many -> function_code_mismatch
  too_large       a padded custom section blows the size cap -> module_too_large
  truncated       the last four bytes are cut          -> section_truncated

Usage:
    python3 tools/gen_x8_mutants.py
    python3 tools/gen_x8_mutants.py --check
    make gen-x8-mutants
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
FIXTURES = REPO / "crates" / "aura-exec" / "tests" / "fixtures"
MUTANTS = FIXTURES / "x8"
MANIFEST = FIXTURES / "x8_mutants.txt"

ARTIFACTS: list[tuple[str, Path]] = [
    ("kv", REPO / "examples" / "kv" / "wasm" / "kv.wasm"),
    ("store", REPO / "examples" / "store" / "wasm" / "store.wasm"),
    ("events", REPO / "examples" / "events" / "wasm" / "events.wasm"),
    ("vault", REPO / "examples" / "vault" / "wasm" / "vault.wasm"),
    ("evil", REPO / "examples" / "evil" / "wasm" / "evil.wasm"),
    ("recurse", REPO / "examples" / "recurse" / "wasm" / "recurse.wasm"),
]

HEADER = """\
# X8 mutant corpus — generated by tools/gen_x8_mutants.py.
#
# Each line names a file, the artifact it was derived from, the kind of damage and
# the verdict the verifier must produce. `expect=accept` lines are the shipped
# artifacts: the corpus proves both halves, not only that bad modules are refused.
#
# Regenerating this file must reproduce every byte of every mutant.
"""


def leb(value: int) -> bytes:
    out = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        if value:
            out.append(byte | 0x80)
        else:
            out.append(byte)
            return bytes(out)


def decode_u32(data: bytes, at: int) -> tuple[int, int]:
    result = 0
    shift = 0
    while True:
        byte = data[at]
        at += 1
        result |= (byte & 0x7F) << shift
        if byte & 0x80 == 0:
            return result, at
        shift += 7


def sections(data: bytes) -> list[dict]:
    """[(id, header_offset, body_offset, body_len)] for every section."""
    out = []
    at = 8
    while at < len(data):
        header = at
        section_id = data[at]
        at += 1
        size, at = decode_u32(data, at)
        out.append({"id": section_id, "header": header, "body": at, "len": size})
        at += size
    return out


IMMEDIATES = {
    # opcode -> (kind, count) ; kind is "u32" | "memarg" | "signed" | "blocktype"
    0x02: ("blocktype", 1),
    0x03: ("blocktype", 1),
    0x04: ("blocktype", 1),
    0x0C: ("u32", 1),
    0x0D: ("u32", 1),
    0x10: ("u32", 1),
    0x11: ("u32", 2),
    0x20: ("u32", 1),
    0x21: ("u32", 1),
    0x22: ("u32", 1),
    0x23: ("u32", 1),
    0x24: ("u32", 1),
    0x41: ("signed", 1),
    0x42: ("signed", 1),
    0x3F: ("u8", 1),
    0x40: ("u8", 1),
}

for _op in range(0x28, 0x3F):
    IMMEDIATES[_op] = ("u32", 2)


def instructions(body: bytes) -> list[tuple[int, int]]:
    """[(offset, opcode)] for every instruction, plus the immediates skipped."""
    out = []
    at = 0
    # Locals: count, then (repeat, type) pairs.
    count, at = decode_u32(body, at)
    for _ in range(count):
        _, at = decode_u32(body, at)
        at += 1
    while at < len(body):
        offset = at
        opcode = body[at]
        at += 1
        out.append((offset, opcode))
        kind_count = IMMEDIATES.get(opcode)
        if kind_count:
            kind, count = kind_count
            for _ in range(count):
                if kind == "u8":
                    at += 1
                else:
                    _, at = decode_u32(body, at)
        elif opcode == 0x0E:  # br_table
            labels, at = decode_u32(body, at)
            for _ in range(labels + 1):
                _, at = decode_u32(body, at)
        elif opcode == 0x43:
            at += 4
        elif opcode == 0x44:
            at += 8
        elif opcode == 0xFC:
            _, at = decode_u32(body, at)
            at += 0
    return out


def code_bodies(data: bytes) -> list[dict]:
    for section in sections(data):
        if section["id"] != 10:
            continue
        at = section["body"]
        count, at = decode_u32(data, at)
        bodies = []
        for _ in range(count):
            size, at = decode_u32(data, at)
            bodies.append({"size_offset": at - len(leb(size)), "body": at, "len": size})
            at += size
        return bodies
    return []


def patch(data: bytes, at: int, payload: bytes) -> bytes:
    return data[:at] + payload + data[at + len(payload):]


def find_first_body(data: bytes) -> dict:
    bodies = code_bodies(data)
    # A body with a healthy instruction count: the biggest one is the safest target.
    return max(bodies, key=lambda body: body["len"])


def first_opcode(data: bytes, wanted: set[int]) -> tuple[dict, int, int] | None:
    for body in code_bodies(data):
        start = body["body"]
        chunk = data[start : start + body["len"]]
        for offset, opcode in instructions(chunk):
            if opcode in wanted:
                return body, start + offset, opcode
    return None


# ---------------------------------------------------------------- mutations


def m_magic(data: bytes) -> tuple[bytes, str]:
    # Byte 0 is the NUL every wasm binary starts with; damage the 'a' of `asm`.
    return patch(data, 1, b"\x01"), "bad_magic"


def m_version(data: bytes) -> tuple[bytes, str]:
    return patch(data, 4, (2).to_bytes(4, "little")), "bad_version"


def m_float_type(data: bytes) -> tuple[bytes, str]:
    for section in sections(data):
        if section["id"] != 1:
            continue
        at = section["body"]
        count, at = decode_u32(data, at)
        for _ in range(count):
            at += 1  # form
            params, at = decode_u32(data, at)
            if params:
                return patch(data, at, b"\x7d"), "float_type"
            at += params
            results, at = decode_u32(data, at)
            if results:
                return patch(data, at, b"\x7d"), "float_type"
            at += results
    raise SystemExit("no typed parameter to damage")


def m_float_local(data: bytes) -> tuple[bytes, str]:
    body = find_first_body(data)
    at = body["body"]
    count, at = decode_u32(data, at)
    if count == 0:
        raise SystemExit("no locals to damage")
    _, at = decode_u32(data, at)
    return patch(data, at, b"\x7c"), "float_type"


def m_import(data: bytes) -> tuple[bytes, str]:
    for section in sections(data):
        if section["id"] != 2:
            continue
        at = section["body"]
        count, at = decode_u32(data, at)
        if count == 0:
            continue
        length, at = decode_u32(data, at)
        name = data[at : at + length]
        if length == 0:
            raise SystemExit("empty import module name")
        # Same length, different module: `env` becomes `xnv`, which is not one of
        # the three ABI surfaces. Rewriting the length instead of the name keeps the
        # section intact, so the refusal is about the *module name* and nothing else.
        damaged = bytes([name[0] ^ 0x01]) + name[1:]
        return patch(data, at, damaged), "import_not_allowed"
    raise SystemExit("no import to damage")


def m_global_type(data: bytes) -> tuple[bytes, str]:
    for section in sections(data):
        if section["id"] != 6:
            continue
        at = section["body"]
        count, at = decode_u32(data, at)
        if count == 0:
            continue
        return patch(data, at, b"\x7d"), "global_type"
    raise SystemExit("no global to damage")


def m_memory_max(data: bytes) -> tuple[bytes, str]:
    for section in sections(data):
        if section["id"] != 5:
            continue
        at = section["body"]
        _, at = decode_u32(data, at)  # count
        flag = data[at]
        if flag != 0x01:
            raise SystemExit("memory has no explicit maximum to damage")
        at += 1
        _, at = decode_u32(data, at)  # min
        max_at = at
        old, at = decode_u32(data, at)
        # Same encoded width, bigger value: the section lengths must stay valid, so
        # only the *value* may change.
        for candidate in (16383, 8191, 4095, 2047, 1023, 511, 255):
            encoded = leb(candidate)
            if len(encoded) == at - max_at and candidate > old:
                return patch(data, max_at, encoded), "memory_limits"
        raise SystemExit("no wider maximum fits the encoding")
    raise SystemExit("no memory section")


def m_opcode(data: bytes) -> tuple[bytes, str]:
    found = first_opcode(data, {0x6A, 0x6B, 0x6C, 0x71, 0x72, 0x74})
    if not found:
        raise SystemExit("no integer arithmetic opcode to damage")
    _, at, _ = found
    return patch(data, at, b"\x92"), "opcode_banned"  # f32.add


def m_call_index(data: bytes) -> tuple[bytes, str]:
    found = first_opcode(data, {0x10})
    if not found:
        raise SystemExit("no call to damage")
    _, at, _ = found
    return patch(data, at + 1, b"\x7f"), "call_index"


def m_local_index(data: bytes) -> tuple[bytes, str]:
    found = first_opcode(data, {0x20, 0x21, 0x22})
    if not found:
        raise SystemExit("no local access to damage")
    _, at, _ = found
    return patch(data, at + 1, b"\x7f"), "local_index"


def m_label_depth(data: bytes) -> tuple[bytes, str]:
    found = first_opcode(data, {0x0C, 0x0D})
    if not found:
        raise SystemExit("no branch to damage")
    _, at, _ = found
    return patch(data, at + 1, b"\x40"), "label_depth"


def m_export_shape(data: bytes) -> tuple[bytes, str]:
    for section in sections(data):
        if section["id"] != 7:
            continue
        at = section["body"]
        count, at = decode_u32(data, at)
        for _ in range(count):
            length, at = decode_u32(data, at)
            name = data[at : at + length]
            if name == b"run":
                return patch(data, at, b"ruN"), "export_shape"
            at += length + 1
            _, at = decode_u32(data, at)
    raise SystemExit("no run export")


def m_function_code(data: bytes) -> tuple[bytes, str]:
    # Drop one body from the code section: the function section still declares N, so
    # the two disagree — which is the check, and it must not be confused with a
    # truncated section.
    for section in sections(data):
        if section["id"] != 10:
            continue
        at = section["body"]
        count, after = decode_u32(data, at)
        smaller = leb(count - 1)
        if len(smaller) != after - at:
            raise SystemExit("count encoding would change length")
        return patch(data, at, smaller), "function_code_mismatch"
    raise SystemExit("no code section")


def m_too_large(data: bytes) -> tuple[bytes, str]:
    # A well-formed custom section, big enough to blow the 1 MiB ceiling.
    payload = b"x8" + b"\x00" * (1_200_000)
    section = b"\x00" + leb(len(payload)) + payload
    return data + section, "module_too_large"


def m_truncated(data: bytes) -> tuple[bytes, str]:
    # Cutting the tail makes the final section claim more bytes than remain: the
    # refusal is `section_truncated`, and the expectation says exactly that.
    return data[: len(data) - 4], "section_truncated"


KINDS: list[tuple[str, callable]] = [
    ("magic", m_magic),
    ("version", m_version),
    ("float_type", m_float_type),
    ("float_local", m_float_local),
    ("import", m_import),
    ("global_type", m_global_type),
    ("memory_max", m_memory_max),
    ("opcode", m_opcode),
    ("call_index", m_call_index),
    ("local_index", m_local_index),
    ("label_depth", m_label_depth),
    ("export_shape", m_export_shape),
    ("function_code", m_function_code),
    ("too_large", m_too_large),
    ("truncated", m_truncated),
]

MUTANTS_PER_KIND = 6
EXTRA_ROUNDS = 2  # the kinds that carry the most weight get a second round


def build() -> tuple[dict[str, bytes], list[str]]:
    files: dict[str, bytes] = {}
    lines: list[str] = []

    for index, (name, path) in enumerate(ARTIFACTS):
        lines.append(f"file=../../../../examples/{name}/wasm/{name}.wasm source={name} kind=shipped expect=accept")

    plan: list[tuple[str, callable]] = []
    for kind, function in KINDS:
        plan.extend([(kind, function)] * MUTANTS_PER_KIND)
    heavy = [
        ("opcode", m_opcode),
        ("label_depth", m_label_depth),
        ("import", m_import),
        ("local_index", m_local_index),
        ("truncated", m_truncated),
    ]
    for _ in range(EXTRA_ROUNDS):
        plan.extend(heavy)
    assert len(plan) == 100, len(plan)

    for index, (kind, function) in enumerate(plan):
        name, path = ARTIFACTS[index % len(ARTIFACTS)]
        data = path.read_bytes()
        try:
            mutated, code = function(data)
        except SystemExit as error:
            raise SystemExit(f"{kind} on {name}: {error}") from error
        assert mutated != data, f"{kind} on {name} was a no-op"
        filename = f"{kind}_{index:03d}_{name}.wasm"
        files[filename] = mutated
        lines.append(
            f"file=x8/{filename} source={name} kind={kind} expect=reject:{code}"
        )
    return files, lines


def main() -> int:
    check = "--check" in sys.argv[1:]
    files, lines = build()
    manifest = HEADER + "\n".join(lines) + "\n"

    if check:
        problems = 0
        current = MANIFEST.read_text(encoding="utf-8") if MANIFEST.exists() else ""
        if current != manifest:
            print("x8_mutants.txt: DRIFT")
            problems += 1
        on_disk = {path.name: path.read_bytes() for path in sorted(MUTANTS.glob("*.wasm"))}
        if set(on_disk) != set(files):
            print(f"x8/: file set differs ({len(on_disk)} on disk, {len(files)} generated)")
            problems += 1
        for name, data in files.items():
            if on_disk.get(name) != data:
                print(f"x8/{name}: DRIFT")
                problems += 1
        if problems:
            return 1
        print(f"x8 mutant corpus: up to date ({len(files)} mutants + {len(ARTIFACTS)} shipped)")
        return 0

    if MUTANTS.exists():
        shutil.rmtree(MUTANTS)
    MUTANTS.mkdir(parents=True)
    for name, data in files.items():
        (MUTANTS / name).write_bytes(data)
    MANIFEST.write_text(manifest, encoding="utf-8")
    total = sum(len(data) for data in files.values())
    print(
        f"wrote {len(files)} mutants ({total} bytes) + {len(ARTIFACTS)} accepted artifacts "
        f"-> {MANIFEST.relative_to(REPO)}"
    )
    kinds = sorted({line.split("kind=")[1].split()[0] for line in lines})
    print(f"kinds: {', '.join(kinds)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
