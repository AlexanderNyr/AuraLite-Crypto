#!/usr/bin/env python3
"""Write W3 evidence (`docs/evidence/w3/`).

Reproducible bundle for the W3 gate ("air-gapped scenario end-to-end; NC:
signature with a foreign domain -> reject"): captures `make test-w3` (the
24-vector suite), `tools/nc_w3.py` (the mutation controls), and inventories
the pinned fixture against the independent generator. Model:
tools/write_w2_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "w3"
FIXTURE = ROOT / "crates/aura-wallet/tests/fixtures/w3_offline_vectors.json"
GENERATOR = ROOT / "tools/gen_w3_vectors.py"
RUNNER = ROOT / "crates/aura-wallet/tests/w3_offline.rs"
NAMED = "verify_foreign_domain"
TOTAL_NC = 418  # 412 through W2 + 6 W3 controls


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    test_log = run(["cargo", "test", "-p", "aura-wallet", "--features",
                    "insecure-test-kdf", "--test", "w3_offline"])
    (EVIDENCE / "test-w3.log").write_text(test_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_w3.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    cases = doc["cases"]
    named_found = any(
        c["name"] == NAMED
        and c["expect_exit"] == 65
        and any("signature verification failed" in line for line in c["expect_stderr"])
        for c in cases
    )
    inv = [
        "# W3 inventory (generated by tools/write_w3_evidence.py)",
        f"gate={doc['gate']}",
        f"vectors={len(cases)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"fixtures_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"runner_sha256={sha256(RUNNER)}",
        "cases:",
    ]
    inv += [f"  {c['name']} exit={c['expect_exit']}" for c in cases]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    report = f"""# W3 closeout report — air-gapped offline signing

Date: 2026-11-11. Gate (WALLET_PLAN row W3): "air-gapped scenario end-to-end;
NC: signature with a foreign domain -> reject" — **satisfied**.

- **Air-gapped end-to-end**: `tx-prepare` (keyless, online) -> USB file or QR
  frames -> `tx-sign` (offline keystore) -> back -> `tx-verify` (online) and
  `broadcast` accepts the signed envelope directly. Vectors `e2e_usb`,
  `e2e_qr`, `e2e_broadcast` walk the full scenario byte-for-byte.
- **Named control**: `verify_foreign_domain` — a signature computed under a
  foreign (domain-less) digest is refused (`error: signature verification
  failed`, exit 65). Mutation NC-1 (`tools/nc_w3.py`) drops the domain-bound
  verification and requires this test to go red.
- **Vectors**: 24 deterministic cases from the independent oracle
  `tools/gen_w3_vectors.py` (AURALITE-OFFLINE-V1 envelope, QR framing,
  BLAKE3, Ed25519 RFC 8032-checked, C2/C4 encoders), asserted byte-for-byte
  by `tests/w3_offline.rs` (25/25 with the count guard).
- **Mutation controls**: 6/6 PASS (foreign domain accepted, envelope checksum
  skipped, signer binding dropped, QR gap accepted, QR duplicate accepted,
  `--against` comparison skipped).
- **Decisions** (docs/w3-offline-plan.md): D-W3-1 deterministic envelope with
  unkeyed BLAKE3 checksum (corruption detection only; the signature is the
  authentication), D-W3-2 QR frames `ALO1:ii/nn:chunk`, D-W3-3 fixed
  verification order with the W2 chain-binding message reused, D-W3-4 no new
  secrets (`tx-sign` reuses the W2 keystore flow).

Receipts: `gates.txt`, `test-w3.log`, `nc.log`, `inventory.txt`, `SHA256SUMS`.
Regenerate with `make evidence-w3`. Public test data only — never use for funds.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    gates = [
        "# W3 gates",
        "air-gapped e2e + 24 vectors: PASS (25 tests: 24 vectors + count guard)"
        if "test result: ok. 25 passed" in test_log
        else "air-gapped e2e + 24 vectors: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)" if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [FIXTURE, GENERATOR, RUNNER,
                  ROOT / "tools/nc_w3.py", ROOT / "crates/aura-wallet/src/offline.rs",
                  EVIDENCE / "test-w3.log", EVIDENCE / "nc.log",
                  EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                  EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# W3 evidence — air-gapped offline signing (24 CLI vectors)

Gate (WALLET_PLAN row W3): "air-gapped scenario end-to-end; NC: signature with
a foreign domain -> reject". All fixtures are PUBLIC TEST DATA ONLY — never
use for funds.

- `test-w3.log` — `cargo test --features insecure-test-kdf --test w3_offline`:
  {len(cases)} vectors plus `vectors_file_has_exactly_24_unique_cases`,
  byte-for-byte against the independent oracle.
- `nc.log` — `tools/nc_w3.py` mutation controls (6): each source mutation must
  turn its named test red; compilation failure is not a valid red.
- `inventory.txt` — the 24 cases with exit codes, the named control, the
  cumulative NC total ({TOTAL_NC}) and SHA-256 pins of fixture, generator, runner.
- `report.md`, `gates.txt` — closeout report and gate summary.
- `SHA256SUMS` — digests of the deliverables and evidence files.

The vectors are produced by `tools/gen_w3_vectors.py` (pure Python: BLAKE3,
Ed25519 RFC 8032, C2/C4 encoders, bech32, BIP-39/SLIP-0010). Regenerate with
`make gen-w3-vectors`; rebuild this bundle with `make evidence-w3`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} ({len(cases)} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
