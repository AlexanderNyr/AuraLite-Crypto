#!/usr/bin/env python3
"""Record the S2 dependency delta (RocksDB + bindgen toolchain).

The C3 baseline is frozen historical evidence. C8/C9 addenda live in
`docs/spec/` and are indexed by the frozen FORMAT_INDEX.md — S2 must not add a
file there (that would break the C10 checksum). S2 records its delta in
`docs/evidence/s2-dependency-addendum.txt`; `tools/check_deps.py` reads both
locations.

Usage:
    python3 tools/record_s2_deps.py
    make record-s2-deps
"""

from __future__ import annotations

import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LOCK = REPO / "Cargo.lock"
OUT = REPO / "docs" / "evidence" / "s2-dependency-addendum.txt"

HEADER = [
    "# AuraLite-Crypto external dependency addendum (S2).",
    "# Generated by tools/record_s2_deps.py from Cargo.lock.",
    "# RocksDB is OPTIONAL (feature `rocksdb`); the default build is pure Rust.",
    "# These crates enter Cargo.lock because of the optional dep and are",
    "# recorded here so check_deps.py can verify exact pins + checksums.",
    "# Native build requires the system librocksdb-dev + clang/libclang.",
]


def read_pairs(path: Path) -> set[tuple[str, str]]:
    result = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            name, version = line.split("=", 1)
            result.add((name, version))
    return result


def main() -> int:
    data = tomllib.loads(LOCK.read_text(encoding="utf-8"))
    current = {
        (package["name"], package["version"])
        for package in data.get("package", [])
        if "source" in package
    }
    known = read_pairs(REPO / "docs" / "spec" / "c3-dependency-allowlist.txt")
    for path in (REPO / "docs" / "spec").glob("*-dependency-addendum.txt"):
        known |= read_pairs(path)
    for path in (REPO / "docs" / "evidence").glob("*-dependency-addendum.txt"):
        if path != OUT:
            known |= read_pairs(path)

    removed = sorted(known - current)
    if removed:
        print(f"ERROR: allowlisted crates disappeared: {removed}")
        return 1
    added = sorted(current - known)
    OUT.write_text(
        "\n".join(HEADER + [f"{name}={version}" for name, version in added]) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(REPO)} ({len(added)} crates added since S1)")
    for name, version in added:
        print(f"  + {name}={version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
