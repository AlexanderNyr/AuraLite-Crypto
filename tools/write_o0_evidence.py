#!/usr/bin/env python3
"""Write O0 evidence (`docs/evidence/o0/`).

Reproducible bundle for the O0 gate ("disable a shard -> CI red (target
registry check)"): captures the 10-scenario CI registry suite,
`tools/nc_o0.py` (the mutation controls), the live registry check against
the workspace tree, and inventories the pinned fixtures against the
independent generator. Model: tools/write_w7_evidence.py.
"""
from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVIDENCE = ROOT / "docs" / "evidence" / "o0"
FIXTURE = ROOT / "crates/aura-testkit/tests/fixtures/o0_ci_vectors.json"
GENERATOR = ROOT / "tools/gen_o0_vectors.py"
RUNNER = ROOT / "crates/aura-testkit/tests/o0_ci.rs"
CI_MODULE = ROOT / "crates/aura-testkit/src/ci.rs"
REGISTRY = ROOT / "ci" / "registry.txt"
NAMED = "disabled_shard_refused"
TOTAL_NC = 674  # 668 through W7 + 6 O0 controls


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd: list[str]) -> str:
    result = subprocess.run(cmd, cwd=ROOT, text=True, capture_output=True, check=False)
    return f"$ {' '.join(cmd)}\n{result.stdout}{result.stderr}exit={result.returncode}\n"


def main() -> int:
    EVIDENCE.mkdir(parents=True, exist_ok=True)

    test_log = run(["cargo", "test", "-p", "aura-testkit", "--test", "o0_ci"])
    (EVIDENCE / "test-o0.log").write_text(test_log, encoding="utf-8")
    nc_log = run([sys.executable, "tools/nc_o0.py"])
    (EVIDENCE / "nc.log").write_text(nc_log, encoding="utf-8")
    registry_log = run(["cargo", "run", "-q", "-p", "aura-testkit", "--bin", "aura-ci",
                        "--", "check"])
    (EVIDENCE / "registry-check.log").write_text(registry_log, encoding="utf-8")
    coverage_log = run(["cargo", "run", "-q", "-p", "aura-testkit", "--bin", "aura-ci",
                        "--", "coverage"])
    (EVIDENCE / "coverage.log").write_text(coverage_log, encoding="utf-8")

    doc = json.loads(FIXTURE.read_text(encoding="utf-8"))
    cases = doc["cases"]
    named_found = any(
        c["name"] == NAMED
        and c.get("nc_ref") == 1
        and c["exit"] == 65
        and "shard security disabled" in c["stderr"]
        for c in cases
    )
    inv = [
        "# O0 inventory (generated by tools/write_o0_evidence.py)",
        f"gate={doc['gate']}",
        f"vectors={len(cases)}",
        f"named_control={NAMED}={'present' if named_found else 'MISSING'}",
        f"fixtures_sha256={sha256(FIXTURE)}",
        f"generator_sha256={sha256(GENERATOR)}",
        f"runner_sha256={sha256(RUNNER)}",
        f"registry_sha256={sha256(REGISTRY)}",
        "cases:",
    ]
    inv += [f"  {c['name']} exit={c['exit']} nc={c.get('nc_ref', '-')}" for c in cases]
    inv.append(f"TOTAL: {TOTAL_NC} negative controls cumulative")
    (EVIDENCE / "inventory.txt").write_text("\n".join(inv) + "\n", encoding="utf-8")

    report = f"""# O0 closeout report — CI baseline (the shard registry)

Date: 2026-11-25. Gate (OPS_PLAN row O0): "disable a shard -> CI red (target
registry check)" — **satisfied**.

- **The gate**: `{NAMED}` (the named control) feeds the checker a registry
  with `shard security disabled` while the lane still holds targets and
  expects `error: ci: shard security disabled` (exit 65); mutation NC-1
  (`tools/nc_o0.py`) drops the enabled-check and the case must turn red.
- **Scenarios**: 10 deterministic cases from the independent oracle
  `tools/gen_o0_vectors.py`, asserted byte-for-byte by `tests/o0_ci.rs`
  (11/11 with the count guard) against `aura_testkit::ci`. Groups: valid
  registry (1), D-O1 command surface (1), refusals (7), coverage report (1).
- **Mutation controls**: 6/6 PASS (disabled-shard check, missing-target
  check, duplicate-target check, shard-set check, empty-shard check,
  unknown-line strictness).
- **Device model** (docs/o0-ci-plan.md): D-O0-1 the plain-text shard
  registry `ci/registry.txt` (the ten lanes of CONTRIBUTING.md over `--lib`
  + `tests/*` targets, each lane pinning its main test; `make ci-sync`
  re-registers); D-O0-2 the target registry check (`aura-ci check`, wired
  into `make test`, incl. the workflow matrix); D-O0-3 no secret shards —
  the format cannot carry commands and `aura-ci run --shard <lane>` emits
  plain `cargo test` forms only; D-O0-4 the deterministic target-coverage
  report (`aura-ci coverage`); D-O0-5 two independent implementations
  (Python oracle vs the shipped Rust checker).
- **CI layout** (`.github/workflows/ci.yml`): `registry` job (`make
  ci-check`), `test` matrix over the ten lanes (`make ci-shard SHARD=<lane>`), a
  `coverage` job (`make coverage`), cargo cache keyed on `Cargo.lock`. Every
  step is a make target — `make test` remains the one local command (D-O1).

Receipts: `gates.txt`, `test-o0.log`, `nc.log`, `registry-check.log`,
`coverage.log`, `inventory.txt`, `SHA256SUMS`. Regenerate with
`make evidence-o0`.
"""
    (EVIDENCE / "report.md").write_text(report, encoding="utf-8")

    gates = [
        "# O0 gates",
        "registry gate + 10 scenarios: PASS (11 tests: 10 scenarios + count guard)"
        if "test result: ok. 11 passed" in test_log
        else "registry gate + 10 scenarios: FAIL",
        f"named control ({NAMED}): {'PASS' if named_found else 'FAIL'}",
        "mutation controls: PASS (6/6)"
        if "RESULT: 6/6 negative controls PASS" in nc_log
        else "mutation controls: FAIL",
        "live registry check: PASS (registry=ok)"
        if "registry=ok" in registry_log and "exit=0" in registry_log
        else "live registry check: FAIL",
    ]
    (EVIDENCE / "gates.txt").write_text("\n".join(gates) + "\n", encoding="utf-8")
    failed = [gate for gate in gates if gate.endswith("FAIL")]
    if failed:
        print("O0 EVIDENCE: FAIL — " + "; ".join(failed))
        return 1

    sums = [
        f"{sha256(p)}  {p.relative_to(ROOT)}"
        for p in [FIXTURE, GENERATOR, RUNNER, CI_MODULE, REGISTRY,
                  ROOT / "tools/nc_o0.py",
                  ROOT / ".github/workflows/ci.yml",
                  EVIDENCE / "test-o0.log", EVIDENCE / "nc.log",
                  EVIDENCE / "registry-check.log", EVIDENCE / "coverage.log",
                  EVIDENCE / "inventory.txt", EVIDENCE / "gates.txt",
                  EVIDENCE / "report.md"]
    ]
    (EVIDENCE / "SHA256SUMS").write_text("\n".join(sums) + "\n", encoding="utf-8")

    readme = f"""# O0 evidence — CI baseline (10 scenarios)

Gate (OPS_PLAN row O0): "disable a shard -> CI red (target registry check)".

- `test-o0.log` — `cargo test -p aura-testkit --test o0_ci`: {len(cases)}
  scenarios plus `vectors_file_has_exactly_10_unique_cases`, byte-for-byte
  against the independent oracle.
- `nc.log` — `tools/nc_o0.py` mutation controls (6): each source mutation must
  turn its named test red; compilation failure is not a valid red.
- `registry-check.log`, `coverage.log` — `aura-ci check` / `aura-ci coverage`
  against the live `ci/registry.txt` and the discovered workspace targets.
- `inventory.txt` — the 10 cases with exit codes and NC refs, the named
  control, the cumulative NC total ({TOTAL_NC}) and SHA-256 pins of fixture,
  generator, runner, registry.
- `report.md`, `gates.txt` — closeout report and gate summary.
- `SHA256SUMS` — digests of the deliverables and evidence files.

The vectors are produced by `tools/gen_o0_vectors.py` (pure Python). The
registry is refreshed with `make ci-sync`; rebuild this bundle with
`make evidence-o0`.
"""
    (EVIDENCE / "README.md").write_text(readme, encoding="utf-8")
    print(f"wrote {EVIDENCE.relative_to(ROOT)} ({len(cases)} vectors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
