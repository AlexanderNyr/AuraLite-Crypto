#!/usr/bin/env python3
"""Record the exact external dependency set in docs/spec/.

This is a DELIBERATE, reviewable action: run it only when a phase adds,
updates or removes a dependency. The output is byte-stable (no timestamps),
so `make gen-c3-vectors` / evidence regeneration never churn it.

Usage:
    python3 tools/record_c3_deps.py
    make record-c3-deps
"""

from __future__ import annotations

import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
LOCK = REPO / "Cargo.lock"
OUT = REPO / "docs" / "spec" / "c3-dependency-allowlist.txt"

HEADER = [
    "# AuraLite-Crypto external dependency allowlist (C3).",
    "# Generated by tools/record_c3_deps.py from Cargo.lock.",
    "# Checked by tools/check_deps.py inside `make test`.",
    "# Lines are name=version; duplicate names with distinct versions are",
    "# intentional (e.g. cpufeatures 0.2/0.3, syn 2/3).",
    "# Any change requires a dedicated phase patch, review and an NC.",
    "# Full cargo deny (licences + advisories) arrives with H1.",
]


def external_packages() -> list[tuple[str, str]]:
    data = tomllib.loads(LOCK.read_text(encoding="utf-8"))
    result = []
    for package in data.get("package", []):
        if "source" in package:
            result.append((package["name"], package["version"]))
    return sorted(result)


def main() -> int:
    packages = external_packages()
    if not packages:
        print("ERROR: no external packages found in Cargo.lock")
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    lines = HEADER + [f"{name}={version}" for name, version in packages]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO)} ({len(packages)} external packages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
