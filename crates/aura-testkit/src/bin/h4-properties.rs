//! H4 property campaign binary (docs/h4-property-plan.md §1, D-H4-4).
//!
//! Generates `--txs` deterministic transfer transactions (Lcg seeds from
//! 20261180), each fully signed and verified and canonically round-tripped,
//! then applied through the production `Account::{credit,debit}` ops on
//! copies that commit together or not at all. After EVERY transaction the
//! invariant `sum(balances) == accounts × start` is checked.
//!
//! `--dump-vectors PATH` writes cross-language differential cases (tx byte
//! layouts and S1 merkle roots) for `tools/h4_reference.py check`.
//! `--differential PATH` verifies cases generated by `tools/h4_reference.py
//! gen`. The line format is stable and versioned with `h4-diff-v1`.

use std::fmt::Write as _;
use std::path::PathBuf;

use aura_crypto::{blake3_hash, ed25519_public_key};
use aura_state::{Account, MerkleTree};
use aura_testkit::Lcg;
use aura_tx::{Tx, TxKind, TxParams, UnsignedTx};
use aura_types::{Amount, ChainId, Gas, Hash, Height, Nonce};

const START: u128 = 1_000_000;
const ACCOUNTS: usize = 16;

fn account_seed(index: usize) -> [u8; 32] {
    let mut seed = [0u8; 32];
    seed[0] = index as u8;
    seed[31] = (index as u8).wrapping_add(0x5a);
    seed[15] = 0xc0;
    seed
}

fn signed_tx(index: usize, nonce: u64, amount: u128) -> Tx {
    let seed = account_seed(index);
    let pk = ed25519_public_key(&seed);
    let params = TxParams {
        chain_id: ChainId::new("h4-chain").unwrap(),
        signer: aura_tx::signer_address(&pk),
        nonce: Nonce::new(nonce),
        kind: TxKind::Transfer,
        payload: amount.to_le_bytes().to_vec(),
        gas_limit: Gas::new(1_000),
        max_fee: Amount::from_units(10),
        tip: Amount::from_units(1),
        expiry: Height::new(100),
    };
    UnsignedTx::new(params).unwrap().sign(&seed).unwrap()
}

fn apply_transfer(accounts: &mut [Account], from: usize, to: usize, amount: u128) -> bool {
    let mut payer = accounts[from];
    let mut payee = accounts[to];
    let ok = payer
        .debit(Amount::from_units(amount))
        .and_then(|()| payee.credit(Amount::from_units(amount)))
        .is_ok()
        && payer.bump_nonce().is_ok();
    if ok {
        accounts[from] = payer;
        accounts[to] = payee;
    }
    ok
}

fn tree_case_root(entries: &[(Hash, Vec<u8>)]) -> Hash {
    let mut tree = MerkleTree::new();
    for (path, value) in entries {
        tree.insert_digest(*path, value.clone());
    }
    tree.tree_root()
}

/// Deterministic case paths: the 32-byte LE encoding of the case number.
fn case_path(i: u64) -> Hash {
    let mut bytes = [0u8; 32];
    bytes[..8].copy_from_slice(&i.to_le_bytes());
    Hash::from_bytes(bytes)
}

fn dump_vectors(path: &PathBuf) -> Result<(), String> {
    let mut out = String::new();
    out.push_str("h4-diff-v1\n");
    for case in 0..64u64 {
        let tx = signed_tx(case as usize % ACCOUNTS, case, (case + 1) as u128);
        let _ = writeln!(
            out,
            "tx {case} {} {} {} {}",
            case as usize % ACCOUNTS,
            case,
            case + 1,
            hex(&tx.to_bytes())
        );
    }
    for case in 0..32u64 {
        let count = 1 + case % 8;
        let entries: Vec<(Hash, Vec<u8>)> = (0..count)
            .map(|j| {
                let value_len = (case + j) % 24;
                let value: Vec<u8> = (0..value_len).map(|k| (case + j + k) as u8).collect();
                (case_path(case * 32 + j), value)
            })
            .collect();
        let mut rendered = Vec::new();
        for (path, value) in &entries {
            rendered.push(format!("{}:{}", hex(path.as_bytes()), hex(value)));
        }
        let root = tree_case_root(&entries);
        let _ = writeln!(
            out,
            "tree {case} {} {}",
            rendered.join(","),
            hex(root.as_bytes())
        );
    }
    std::fs::write(path, out).map_err(|e| format!("write {path:?}: {e}"))
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

fn unhex(text: &str) -> Result<Vec<u8>, String> {
    if !text.len().is_multiple_of(2) {
        return Err(format!("odd hex length: {text}"));
    }
    (0..text.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&text[i..i + 2], 16).map_err(|e| e.to_string()))
        .collect()
}

fn check_differential(path: &PathBuf) -> Result<(), String> {
    let text = std::fs::read_to_string(path).map_err(|e| format!("read {path:?}: {e}"))?;
    let mut checked = 0usize;
    for (lineno, line) in text.lines().enumerate() {
        if line.is_empty() || line.starts_with("h4-diff-v1") {
            continue;
        }
        let fields: Vec<&str> = line.split(' ').collect();
        match fields.as_slice() {
            ["tx", _case, index, nonce, amount, bytes] => {
                let tx = signed_tx(
                    index.parse().map_err(|e| format!("line {lineno}: {e}"))?,
                    nonce.parse().map_err(|e| format!("line {lineno}: {e}"))?,
                    amount.parse().map_err(|e| format!("line {lineno}: {e}"))?,
                );
                let expected = unhex(bytes)?;
                if tx.to_bytes() != expected {
                    return Err(format!(
                        "H4: canonical roundtrip violated (line {lineno}: rust bytes differ from reference)"
                    ));
                }
                checked += 1;
            }
            ["tree", _case, entries, root] => {
                let mut parsed = Vec::new();
                for item in entries.split(',') {
                    let (path_hex, value_hex) = item
                        .split_once(':')
                        .ok_or_else(|| format!("line {lineno}: bad entry"))?;
                    let path = unhex(path_hex)?;
                    let path = Hash::from_bytes(path.as_slice().try_into().unwrap());
                    parsed.push((path, unhex(value_hex)?));
                }
                let expected = unhex(root)?;
                if tree_case_root(&parsed).as_bytes() != expected.as_slice() {
                    return Err(format!("H4: tree differential mismatch (line {lineno})"));
                }
                checked += 1;
            }
            _ => return Err(format!("line {lineno}: unknown case")),
        }
    }
    println!("differential_check=ok cases={checked}");
    Ok(())
}

fn main() -> Result<(), String> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let option = |name: &str| -> Option<String> {
        args.iter()
            .position(|arg| arg == name)
            .and_then(|index| args.get(index + 1))
            .cloned()
    };
    if let Some(path) = option("--dump-vectors") {
        return dump_vectors(&PathBuf::from(path));
    }
    if let Some(path) = option("--differential") {
        return check_differential(&PathBuf::from(path));
    }
    let txs: u64 = option("--txs")
        .ok_or("usage: h4-properties --txs N [--seed S]")?
        .parse()
        .map_err(|e| format!("--txs: {e}"))?;
    let seed: u64 = option("--seed")
        .map(|value| value.parse().map_err(|e| format!("--seed: {e}")))
        .transpose()?
        .unwrap_or(20261180);

    let mut accounts: Vec<Account> = (0..ACCOUNTS)
        .map(|_| {
            Account::new(
                Nonce::new(0),
                Amount::from_units(START),
                Hash::ZERO,
                Hash::ZERO,
            )
        })
        .collect();
    let mut nonces = [0u64; ACCOUNTS];
    let total = |accounts: &[Account]| -> u128 {
        accounts.iter().map(|account| account.balance.units()).sum()
    };
    let start_total = total(&accounts);

    let mut lcg = Lcg::new(seed);
    let mut committed = 0u64;
    let mut rejected = 0u64;
    let mut digest = blake3_hash(b"AuraLite-Crypto/h4-tx-digest-v1\0");

    for round in 0..txs {
        let from = (lcg.next_u64() as usize) % ACCOUNTS;
        let to = (lcg.next_u64() as usize) % ACCOUNTS;
        if from == to {
            continue;
        }
        let amount = 1 + (lcg.next_u64() as u128) % 200_000;

        let tx = signed_tx(from, nonces[from], amount);
        tx.verify_signature()
            .map_err(|e| format!("round {round}: signature property violated: {e}"))?;
        let bytes = tx.to_bytes();
        let parsed = Tx::from_canonical_bytes(&bytes)
            .map_err(|e| format!("round {round}: canonical roundtrip violated: {e}"))?;
        if parsed != tx || parsed.to_bytes() != bytes {
            return Err(format!("round {round}: canonical roundtrip violated"));
        }
        let mut chain = digest.as_bytes().to_vec();
        chain.extend_from_slice(tx.txid().as_bytes());
        digest = blake3_hash(&chain);

        let before = total(&accounts);
        if apply_transfer(&mut accounts, from, to, amount) {
            committed += 1;
            if total(&accounts) != before {
                return Err(format!("round {round}: balance conservation violated"));
            }
            nonces[from] += 1;
        } else {
            rejected += 1;
            let mut trial = accounts.clone();
            let _ = apply_transfer(&mut trial, from, to, amount);
            if trial != accounts {
                return Err(format!(
                    "round {round}: rejected transfer must not change state"
                ));
            }
        }
        if total(&accounts) != start_total {
            return Err(format!("round {round}: balance conservation violated"));
        }
    }

    println!("txs={}", txs);
    println!("committed={committed}");
    println!("rejected={rejected}");
    println!("sum_checks={}", committed + rejected);
    println!("final_total={}", total(&accounts));
    println!("start_total={start_total}");
    println!("digest={}", hex(digest.as_bytes()));
    println!("seed={seed}");
    println!("RESULT: balance conservation holds over {txs} generated txs");
    Ok(())
}
